const areas = ['Document', 'HouseProfile', 'Extension', 'View', 'Lineage'];
const collections = ['persons', 'partnerships', 'parentages', 'houses', 'cadetBranches', 'timeJumps'];
const managed = key => (key.startsWith('registryManaged') && key !== 'registryManagedEntitySourceRevision')
  || ['houseLoreCorrectionInventory', 'houseLifeStatusCorrectionInventory'].includes(key);

/** Retain the pre-existing maps while keeping the biography feature's other work. */
export function withoutInheritedBiographyMaps(original, biographed) {
  const extensions = { ...biographed.extensions };
  for (const area of areas) {
    const key = `registryManaged${area}FieldRevisions`;
    if (Object.hasOwn(original.extensions, key)) extensions[key] = original.extensions[key];
    else delete extensions[key];
  }
  return { ...biographed, extensions };
}

/** Describe only migration metadata generated by source-owned wrappers. */
export function sourceMetadataProvenance(previous, current) {
  const fields = [], historicalObjectOrders = [];
  const inspect = (before = {}, after = {}, path) => {
    const start = fields.length;
    for (const key of new Set([...Object.keys(before), ...Object.keys(after)])) {
      if (!managed(key) || JSON.stringify(before[key]) === JSON.stringify(after[key])
        && Object.hasOwn(before, key) === Object.hasOwn(after, key)) continue;
      fields.push({ path: [...path, key], beforePresent: Object.hasOwn(before, key),
        ...(Object.hasOwn(before, key) ? { before: structuredClone(before[key]) } : {}),
        afterPresent: Object.hasOwn(after, key),
        ...(Object.hasOwn(after, key) ? { after: structuredClone(after[key]) } : {}) });
    }
    if (fields.length > start) {
      historicalObjectOrders.push({ path, keys: Object.keys(before) });
    }
  };
  inspect(previous.extensions, current.extensions, ['family', 'extensions']);
  for (const collection of collections) {
    const byId = new Map(previous[collection].map(entity => [entity.id, entity]));
    for (const entity of current[collection]) {
      const before = byId.get(entity.id);
      if (!before) continue;
      const path = ['family', collection, `@${entity.id}`, 'extensions'];
      if (!Object.hasOwn(before, 'extensions') && entity.extensions
        && Object.keys(entity.extensions).every(managed)) {
        fields.push({ path, beforePresent: false, afterPresent: true,
          after: structuredClone(entity.extensions) });
      } else inspect(before.extensions, entity.extensions, path);
    }
  }
  return { fields, historicalObjectOrders };
}
