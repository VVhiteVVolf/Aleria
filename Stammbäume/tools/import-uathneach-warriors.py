"""Copy the reviewed Uathneach originals and retain the three missing-clan proposals.

Original PNGs are copied byte-for-byte. WebP previews retain alpha and aspect ratio.
No source folder files are written, moved, cleaned or deleted.
"""
from pathlib import Path
import hashlib
import json
import shutil
from PIL import Image


ROOT = Path(__file__).resolve().parents[2]
STAMM = ROOT / "Stammb\u00e4ume"
SELECTION = STAMM / "assets/data/family-sources/uathneach-warriors.source.json"
INVENTORY = STAMM / "assets/data/source-inventories/uathneach-warriors-2026-10-27.json"
CATALOG = STAMM / "assets/js/data/uathneach-warriors.js"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    source = json.loads(SELECTION.read_text(encoding="utf-8"))
    structure = json.loads((STAMM / "assets/js/data/uathneach-territories.source.json").read_text(encoding="utf-8"))
    clans = {c["id"]: c for c in structure["clans"]}
    entries = source["entries"]
    if len(entries) != len(clans) or {e["id"] for e in entries} != set(clans):
        raise ValueError("Illustration roster differs from confirmed Uathneach clans")
    catalog, inventory = [], []
    for entry in entries:
        clan = clans[entry["id"]]
        original = ROOT / f"Vorschau/Uathneach/assets/warriors/production/{entry['id']}.png" if entry.get("generated") else Path(source["sourceDirectory"]) / entry["file"]
        destination = STAMM / f"assets/images/references/{clan['familyId']}/krieger.png"
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.exists() or sha(original) != sha(destination):
            shutil.copyfile(original, destination)
        preview = destination.with_suffix(".webp")
        with Image.open(original) as image:
            width, height = image.size
            rgba = image.convert("RGBA")
            rgba.thumbnail((768, 1152), Image.Resampling.LANCZOS)
            rgba.save(preview, "WEBP", quality=94, method=4, exact=True)
        profile = json.loads((ROOT / f"Klassenordner/Alben/{entry['classId']}/klasse.json").read_text(encoding="utf-8"))
        image_path = "/" + preview.relative_to(ROOT).as_posix()
        fullsize = "/" + destination.relative_to(ROOT).as_posix()
        catalog.append({"id":entry["id"], "familyId":clan["familyId"], "name":clan["name"],
                        "classId":entry["classId"], "className":profile["name"], "sourceKind":"generated" if entry.get("generated") else "supplied",
                        "equipment":entry["equipment"], "reason":"Erhaltene ergänzende Darstellung für diesen Clan." if entry.get("generated") else "Vom Nutzer gelieferte Clangestaltung; Ausrüstung und Bildkomposition bleiben erhalten.",
                        "palette":entry.get("palette",[]), "mounted":False, "horse":None, "image":image_path, "fullsize":fullsize, "width":width, "height":height})
        inventory.append({"id":entry["id"], "familyId":clan["familyId"], "role":"warrior", "path":destination.relative_to(STAMM).as_posix(),
                          "sourceKind":catalog[-1]["sourceKind"], "original":str(original), "sourceSha256":sha(original), "sha256":sha(destination),
                          "preview":preview.relative_to(ROOT).as_posix(), "previewSha256":sha(preview), "width":width, "height":height})
    INVENTORY.write_text(json.dumps({"schema":"aleria.uathneach.warrior-inventory", "reviewedAt":source["reviewedAt"], "selection":SELECTION.relative_to(ROOT).as_posix(), "images":inventory},ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    CATALOG.write_text("// Generated by Stammb\u00e4ume/tools/import-uathneach-warriors.py. Edit the reviewed selection.\nexport const UATHNEACH_WARRIORS=Object.freeze("+json.dumps(catalog,ensure_ascii=False,indent=2)+".map(Object.freeze));\n",encoding="utf-8")
    print(json.dumps({"clans":len(catalog),"supplied":sum(c["sourceKind"]=="supplied" for c in catalog),"retained":sum(c["sourceKind"]=="generated" for c in catalog)}))


if __name__ == "__main__":
    main()
