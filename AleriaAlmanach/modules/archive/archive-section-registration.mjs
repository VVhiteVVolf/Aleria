// Build-time registration shared by organization catalogs. The existing archive
// owns tree nodes, user moves and overrides; this only places builtin entries.
export function renderArchiveSectionRegistration(functionName, modules, sourceName) {
  if (!/^[a-zA-Z][a-zA-Z0-9]*$/.test(functionName)) throw new Error('Invalid registration function name.');
  for (const module of modules) {
    if (!module.tab || !(module.entry?.id || module.entryId) || (module.path && (!Array.isArray(module.path) || module.path.some(part => typeof part !== 'string' || !part.trim())))) {
      throw new Error('Invalid organization section definition.');
    }
  }
  return `// Generated by ${sourceName}. Edit the feature models.
(function ${functionName}() {
  const modules = ${JSON.stringify(modules, null, 2)};
  for (const module of modules) {
    const path = module.path || [];
    const entryId = module.entry?.id || module.entryId;
    const previous = SECTIONS.find(candidate => candidate.entries?.some(entry => entry.id === entryId));
    const entry = previous?.entries.find(entry => entry.id === entryId) || module.entry;
    if (!entry) continue;
    let section = SECTIONS.find(candidate => candidate.tab === module.tab && JSON.stringify(candidate.path || []) === JSON.stringify(path));
    if (!section) {
      section = { key: path.at(-1) || module.tab, tab: module.tab, path, desc: module.description || '', ...(module.icon ? { iconUrl: module.icon } : {}), entries: [] };
      SECTIONS.push(section);
    }
    if (previous === section) continue;
    if (previous) previous.entries = previous.entries.filter(candidate => candidate.id !== entryId);
    section.entries.push(entry);
  }
})();
`;
}
