import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { patrickBiographyCharacterIds } from './biography-identities.mjs';
import { createFamilyPersonCandidate, buildFamilyPersonViewUrl } from '../character-genealogy/genealogy-mapping.js';
import { createFolderPathFromHouseProfile } from '../../../Stammbäume/assets/js/domain/house-profile.js';
import { HOUSE_SGRECHIWR_FAMILY } from '../../../Stammbäume/assets/js/data/house-sgrechiwr-family.js';
import { HOUSE_DRAENMELYN_FAMILY } from '../../../Stammbäume/assets/js/data/house-draenmelyn-family.js';
import { HOUSE_SWYLL_FAMILY } from '../../../Stammbäume/assets/js/data/house-swyll-family.js';
import { HOUSE_HAMNETT_FAMILY } from '../../../Stammbäume/assets/js/data/house-hamnett-family.js';

const input=new URL('source/biographies-2026-11-03.json',import.meta.url);
const source=JSON.parse(await readFile(input,'utf8'));
assert.equal(source.schema,'aleria.patrick-biography-sources');
assert.equal(source.schemaVersion,1);
assert.deepEqual(new Set(source.entries.map(row=>row.characterId)),new Set(patrickBiographyCharacterIds()));
for(const row of source.entries){
  assert.equal(row.key,row.worldPersonId);
  assert(row.personId&&row.biographyModule?.biography&&row.narrativeFingerprints.length);
  assert(Object.keys(row).every(key=>['key','characterId','worldPersonId','personId','name','aliases','personFields','residence','birthplace','statCorrections','connectionImageSupplements','biographyModule','narrativeFingerprints','provenance'].includes(key)));
}
const workspace=new URL('../../../',import.meta.url);
const assetRewrites={};
function examineAssets(value,field=''){
  if(Array.isArray(value)){value.forEach(child=>examineAssets(child,field));return;}
  if(value&&typeof value==='object'){for(const [key,child]of Object.entries(value))examineAssets(child,key);return;}
  if(typeof value!=='string'||!['portrait','portraitStages','image','icon'].includes(field))return;
  let url;try{url=new URL(value,'https://dieweltvonaleria.netlify.app');}catch{return;}
  if(!['dieweltvonaleria.netlify.app','www.dieweltvonaleria.netlify.app'].includes(url.hostname))return;
  const decoded=decodeURIComponent(url.pathname);
  if(!decoded.startsWith('/stammbäume/'))return;
  const corrected='/Stammbäume/'+decoded.slice('/stammbäume/'.length);
  assert(!corrected.split('/').includes('..'));
  if(existsSync(new URL(`.${corrected}`,workspace)))assetRewrites[value]=corrected+url.search+url.hash;
}
for(const row of source.entries){
  examineAssets(row.biographyModule);
  for(const supplement of row.connectionImageSupplements||[])assert(existsSync(new URL(`.${supplement.image}`,workspace)),'Ergänztes Verbindungsbild fehlt lokal.');
  const candidates=[HOUSE_SGRECHIWR_FAMILY,HOUSE_DRAENMELYN_FAMILY,HOUSE_SWYLL_FAMILY,HOUSE_HAMNETT_FAMILY].flatMap(family=>family.persons
    .filter(person=>person.worldPersonId===row.worldPersonId).map(person=>createFamilyPersonCandidate({id:family.document.id,title:family.document.title,
      folderPath:createFolderPathFromHouseProfile(family.document.houseProfile),family},person)));
  assert(candidates.length,'Bestehende Weltperson fehlt in den kanonischen Familien.');
  const preferred=candidates.find(candidate=>candidate.familyId==='haus-sgrechiwr')||candidates.find(candidate=>candidate.familyRole==='core')||candidates[0];
  const relationships=Object.fromEntries(['parents','partners','children'].map(kind=>[kind,[...new Map(candidates.flatMap(candidate=>candidate.relationships[kind]).map(relation=>[relation.worldPersonId||relation.personId,relation])).values()]]));
  row.genealogyCandidate={...preferred,relationships};
  row.familySources=candidates.map(candidate=>({familyId:candidate.familyId,personId:candidate.personId,url:buildFamilyPersonViewUrl(candidate),fingerprint:candidate.fingerprint}));
  row.residenceFolderPath=createFolderPathFromHouseProfile(HOUSE_SWYLL_FAMILY.document.houseProfile);
}
source.assetRewrites=assetRewrites;
const target=new URL('biography-source.generated.mjs',import.meta.url);
const output=`// Generated by build-biography-source.mjs from the three approved public biographies.\nexport const PATRICK_BIOGRAPHY_SOURCE = ${JSON.stringify(source,null,2)};\n`;
if(process.argv.includes('--check'))assert.equal(await readFile(target,'utf8'),output,'Die gemeinsame Biografiequelle ist veraltet.');
else await writeFile(target,output);
console.log(JSON.stringify({checked:process.argv.includes('--check'),publicBiographies:source.entries.length}));
