"""Pack closed puppet parts from generated source PNGs (requires Pillow).

Only crop, uniformly resize, align and encode. Original artwork is retained.
The measured windows follow the actual drawings rather than an assumed grid.
No polygon masks are cut through characters or equipment.
"""
import json
from collections import deque
from pathlib import Path
from PIL import Image, ImageChops, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'assets/loading-screen/source'
DESTINATION = ROOT / 'public/assets/loading-screen'
MODULE = Path(__file__).resolve().parent


def extract(sheet, box):
    part = sheet.crop(box)
    # Keep the connected illustration, remove disconnected remnants of a
    # neighboring grid cell. Dilate by one pixel to retain antialiased edges.
    width, height = part.size
    values = part.getchannel('A').tobytes()
    visited = bytearray(width * height)
    largest = []
    for seed, alpha in enumerate(values):
        if alpha <= 16 or visited[seed]:
            continue
        queue = deque([seed])
        visited[seed] = 1
        component = []
        while queue:
            pixel = queue.popleft()
            component.append(pixel)
            x, y = pixel % width, pixel // width
            for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                nx, ny = x + dx, y + dy
                neighbor = ny * width + nx
                if 0 <= nx < width and 0 <= ny < height and not visited[neighbor] and values[neighbor] > 16:
                    visited[neighbor] = 1
                    queue.append(neighbor)
        if len(component) > len(largest):
            largest = component
    pixels = bytearray(width * height)
    for pixel in largest:
        pixels[pixel] = 255
    clean = Image.frombytes('L', part.size, bytes(pixels)).filter(ImageFilter.MaxFilter(3))
    part.putalpha(ImageChops.multiply(part.getchannel('A'), clean))
    bounds = part.getchannel('A').point(lambda alpha: 255 if alpha > 16 else 0).getbbox()
    if not bounds:
        raise ValueError(f'Empty puppet part: {box}')
    return part.crop(bounds)


def body(name, part):
    scale = min(228 / part.width, 176 / part.height)
    resized = part.resize((round(part.width * scale), round(part.height * scale)), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (256, 256))
    canvas.alpha_composite(resized, ((256 - resized.width) // 2, 12))
    file = f'{name}-body-v4.webp'
    canvas.save(DESTINATION / file, 'WEBP', quality=92, method=6)
    return file


def leg(name, index, part, joint):
    scale = min(50 / part.width, 82 / part.height)
    resized = part.resize((round(part.width * scale), round(part.height * scale)), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (64, 96))
    x = (64 - resized.width) // 2
    canvas.alpha_composite(resized, (x, 5))
    cap = resized.getchannel('A').crop((0, 0, resized.width, 18))
    cap_bounds = cap.point(lambda alpha: 255 if alpha > 100 else 0).getbbox()
    anchor = [round(x + (cap_bounds[0] + cap_bounds[2]) / 2), 14]
    file = f'{name}-leg-{index}-v4.webp'
    canvas.save(DESTINATION / file, 'WEBP', quality=92, method=6)
    return {'file': file, 'joint': joint, 'anchor': anchor, 'width': 64, 'height': 96}


def prepare():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    humans = Image.open(SOURCE / 'travellers-puppet-v4.png').convert('RGBA')
    rows = [0, 318, 628, 922, humans.height]
    hips = {'gawain': [143, 155], 'freya': [143, 157], 'guinevere': [149, 162], 'fenrir': [147, 162]}
    rigs = {}
    for row, name in enumerate(hips):
        windows = [(0, 530), (560, 820), (880, 1180)]
        parts = [extract(humans, (left, rows[row], right, rows[row + 1])) for left, right in windows]
        rigs[name] = {'body': body(name, parts[0]), 'parts': [leg(name, index, parts[index + 1], [hips[name][index], 178]) for index in range(2)]}
    for name, rig in rigs.items():
        pose = Image.new('RGBA', (256, 256))
        for index, part in enumerate(rig['parts']):
            limb = Image.new('RGBA', (256, 256))
            limb.alpha_composite(Image.open(DESTINATION / part['file']).convert('RGBA'), (part['joint'][0] - part['anchor'][0], part['joint'][1] - part['anchor'][1]))
            angle = 30 * (1 if index % 2 == 0 else -1)
            pose.alpha_composite(limb.rotate(-angle, resample=Image.Resampling.BICUBIC, center=tuple(part['joint'])))
        pose.alpha_composite(Image.open(DESTINATION / rig['body']).convert('RGBA'))
        pose.save(DESTINATION / f'{name}-stand-v4.webp', 'WEBP', quality=92, method=6)
    text = json.dumps(rigs, indent=2, ensure_ascii=False)
    (MODULE / 'loading-screen-puppet-data.js').write_text('// Generated by prepare-assets.py from closed, isolated puppet parts.\nexport const LOADING_SCREEN_RIGS = Object.freeze(' + text + ');\n', encoding='utf-8')
    (DESTINATION / 'puppet-manifest.json').write_text(json.dumps({'version': 4, 'rigs': rigs}, indent=2) + '\n', encoding='utf-8')
    print('Prepared 4 closed bodies and 8 complete leg parts.')


if __name__ == '__main__':
    prepare()
