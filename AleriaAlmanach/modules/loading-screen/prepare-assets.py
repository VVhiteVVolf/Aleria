"""Pack closed puppet parts from generated source PNGs (requires Pillow).

Only crop, uniformly resize, align and encode. Original artwork is retained.
The measured windows follow the actual drawings rather than an assumed grid.
No polygon masks are cut through characters or equipment.
"""
import argparse
import hashlib
import json
from collections import deque
from pathlib import Path
from PIL import Image, ImageChops, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'assets/loading-screen/source'
DESTINATION = ROOT / 'public/assets/loading-screen'
MODULE = Path(__file__).resolve().parent


def extract(sheet, box, *, crop=True):
    part = sheet.crop(box)
    # Keep the connected illustration, remove disconnected remnants of a
    # neighboring grid cell. Dilate by one pixel to retain antialiased edges.
    width, height = part.size
    values = part.getchannel('A').tobytes()
    visited = bytearray(width * height)
    largest = []
    for seed, alpha in enumerate(values):
        if alpha <= 16 or visited[seed]:
            continue
        queue = deque([seed])
        visited[seed] = 1
        component = []
        while queue:
            pixel = queue.popleft()
            component.append(pixel)
            x, y = pixel % width, pixel // width
            for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                nx, ny = x + dx, y + dy
                neighbor = ny * width + nx
                if 0 <= nx < width and 0 <= ny < height and not visited[neighbor] and values[neighbor] > 16:
                    visited[neighbor] = 1
                    queue.append(neighbor)
        if len(component) > len(largest):
            largest = component
    pixels = bytearray(width * height)
    for pixel in largest:
        pixels[pixel] = 255
    clean = Image.frombytes('L', part.size, bytes(pixels)).filter(ImageFilter.MaxFilter(3))
    part.putalpha(ImageChops.multiply(part.getchannel('A'), clean))
    bounds = part.getchannel('A').point(lambda alpha: 255 if alpha > 16 else 0).getbbox()
    if not bounds:
        raise ValueError(f'Empty puppet part: {box}')
    return part.crop(bounds) if crop else part


def body(name, part):
    scale = min(228 / part.width, 176 / part.height)
    resized = part.resize((round(part.width * scale), round(part.height * scale)), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (256, 256))
    canvas.alpha_composite(resized, ((256 - resized.width) // 2, 12))
    file = f'{name}-body-v4.webp'
    canvas.save(DESTINATION / file, 'WEBP', quality=92, method=6)
    return file


def leg(name, index, part, joint):
    scale = min(50 / part.width, 82 / part.height)
    resized = part.resize((round(part.width * scale), round(part.height * scale)), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (64, 96))
    x = (64 - resized.width) // 2
    canvas.alpha_composite(resized, (x, 5))
    cap = resized.getchannel('A').crop((0, 0, resized.width, 18))
    cap_bounds = cap.point(lambda alpha: 255 if alpha > 100 else 0).getbbox()
    anchor = [round(x + (cap_bounds[0] + cap_bounds[2]) / 2), 14]
    file = f'{name}-leg-{index}-v4.webp'
    canvas.save(DESTINATION / file, 'WEBP', quality=92, method=6)
    return {'file': file, 'joint': joint, 'anchor': anchor, 'width': 64, 'height': 96}


def prepare():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    humans = Image.open(SOURCE / 'travellers-puppet-v4.png').convert('RGBA')
    rows = [0, 318, 628, 922, humans.height]
    hips = {'gawain': [143, 155], 'freya': [143, 157], 'guinevere': [149, 162], 'fenrir': [147, 162]}
    rigs = {}
    for row, name in enumerate(hips):
        windows = [(0, 530), (560, 820), (880, 1180)]
        parts = [extract(humans, (left, rows[row], right, rows[row + 1])) for left, right in windows]
        rigs[name] = {'body': body(name, parts[0]), 'parts': [leg(name, index, parts[index + 1], [hips[name][index], 178]) for index in range(2)]}
    for name, rig in rigs.items():
        pose = Image.new('RGBA', (256, 256))
        for index, part in enumerate(rig['parts']):
            limb = Image.new('RGBA', (256, 256))
            limb.alpha_composite(Image.open(DESTINATION / part['file']).convert('RGBA'), (part['joint'][0] - part['anchor'][0], part['joint'][1] - part['anchor'][1]))
            angle = 30 * (1 if index % 2 == 0 else -1)
            pose.alpha_composite(limb.rotate(-angle, resample=Image.Resampling.BICUBIC, center=tuple(part['joint'])))
        pose.alpha_composite(Image.open(DESTINATION / rig['body']).convert('RGBA'))
        pose.save(DESTINATION / f'{name}-stand-v4.webp', 'WEBP', quality=92, method=6)
    text = json.dumps(rigs, indent=2, ensure_ascii=False)
    (MODULE / 'loading-screen-puppet-data.js').write_text('// Generated by prepare-assets.py from closed, isolated puppet parts.\nexport const LOADING_SCREEN_RIGS = Object.freeze(' + text + ');\n', encoding='utf-8')
    (DESTINATION / 'puppet-manifest.json').write_text(json.dumps({'version': 4, 'rigs': rigs}, indent=2) + '\n', encoding='utf-8')
    print('Prepared 4 closed bodies and 8 complete leg parts.')


def asset_description(path):
    with Image.open(path) as image:
        return dict(file=path.relative_to(ROOT).as_posix(), size=list(image.size),
                    frames=image.n_frames if hasattr(image, 'n_frames') else 1,
                    bytes=path.stat().st_size, sha256=hashlib.sha256(path.read_bytes()).hexdigest())


def prepare_journey():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    illustrations = [SOURCE / 'highland-road-v5.png', SOURCE / 'travellers-stride-v5.png']
    landscape = Image.open(illustrations[0]).convert('RGB')
    atlas = Image.open(illustrations[1])
    if atlas.mode != 'RGBA':
        raise ValueError('The new walk atlas must have genuine alpha.')

    art_files = []
    for width, suffix, extension, quality, aspect in [
        (1440, 'desktop', 'avif', 54, None),
        (640, 'mobile', 'avif', 54, 1.25),
        (1200, 'fallback', 'webp', 78, None),
    ]:
        source = landscape
        if aspect is not None:
            crop_width = round(landscape.height * aspect)
            left = (landscape.width - crop_width) // 2
            source = landscape.crop((left, 0, left + crop_width, landscape.height))
        file = DESTINATION / f'highland-road-v5-{suffix}.{extension}'
        scaled = source.resize((width, round(width * source.height / source.width)), Image.Resampling.LANCZOS)
        scaled.save(file, quality=quality)
        art_files.append(file)

    cell_size = 152
    packed = Image.new('RGBA', (4 * cell_size, 4 * cell_size))
    frames = []
    for row in range(4):
        strip = []
        for col in range(4):
            bounds = (col * atlas.width // 4, row * atlas.height // 4,
                      (col + 1) * atlas.width // 4, (row + 1) * atlas.height // 4)
            frame = extract(atlas, bounds, crop=False)
            if frame.getchannel('A').getbbox() is None:
                raise ValueError(f'Empty frame at row {row}, column {col}')
            frame = frame.resize((cell_size, cell_size), Image.Resampling.LANCZOS)
            packed.alpha_composite(frame, (col * cell_size, row * cell_size))
            strip.append(frame)
        frames.append(strip)
    file = DESTINATION / 'travellers-stride-v5.webp'
    packed.save(file, quality=84, method=6, exact=True)
    art_files.append(file)

    # Standalone GIF preview with four staggered phases. A common palette lets
    # the encoder store the unchanged landscape only once.
    preview_dir = SOURCE.parent / 'preview'
    preview_dir.mkdir(exist_ok=True)
    preview = preview_dir / 'highland-journey-v5.gif'
    background = landscape.resize((576, 240), Image.Resampling.LANCZOS).convert('RGBA')
    preview_frames = []
    for index in range(4):
        image = background.copy()
        for actor, row in enumerate([3, 2, 1, 0]):
            phase = (index + actor) % 4
            frame = frames[row][phase].resize((94, 94), Image.Resampling.LANCZOS)
            image.alpha_composite(frame, (70 + actor * 107, 109))
        preview_frames.append(image.convert('RGB'))
    palette_source = Image.new('RGB', (background.width, background.height * len(preview_frames)))
    for index, frame in enumerate(preview_frames):
        palette_source.paste(frame, (0, index * background.height))
    palette = palette_source.quantize(colors=192)
    indexed = [frame.quantize(palette=palette, dither=Image.Dither.NONE) for frame in preview_frames]
    indexed[0].save(preview, save_all=True, append_images=indexed[1:], duration=270, loop=0, optimize=True)

    manifest = dict(version=5, sources=[asset_description(file) for file in illustrations],
                    atlas=dict(order=['gawain', 'freya', 'guinevere', 'fenrir'], rows=4, columns=4, cell=cell_size),
                    assets=[asset_description(file) for file in art_files], preview=asset_description(preview))
    (DESTINATION / 'journey-v5-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print('Prepared AVIF/WebP journey, transparent sprite atlas and loop preview.')


def encode_scene_background(name, image, widths):
    assets = []
    encodings = [('desktop', 'avif', 55), ('mobile', 'avif', 54), ('fallback', 'webp', 79)]
    for (size, extension, quality), width in zip(encodings, widths, strict=True):
        file = DESTINATION / f'{name}-{size}.{extension}'
        scaled = image.resize((width, round(width * image.height / image.width)), Image.Resampling.LANCZOS)
        scaled.save(file, quality=quality)
        assets.append(asset_description(file))
    return assets


def prepare_panorama(journey, ground_y):
    name = f'{journey}-panorama-v6'
    original = SOURCE / f'{name}.png'
    with Image.open(original) as landscape:
        height = round(landscape.width / 4)
        # Put all three paths on the same baseline as the walking figures.
        top = ground_y - round(height * .86)
        panorama = landscape.crop((0, top, landscape.width, top + height)).convert('RGB')
    assets = encode_scene_background(name, panorama, (1800, 1160, 1440))
    return dict(source=asset_description(original), groundY=ground_y, assets=assets)


def pack_journey_stride(journey, sheets):
    cell = 160
    actor_count = sum(len(actors) for _, actors, _ in sheets)
    atlas = Image.new('RGBA', (4 * cell, actor_count * cell))
    sources = []
    order = []
    for source_name, actors, row_split in sheets:
        source = SOURCE / f'{source_name}-stride-v6.png'
        sources.append(asset_description(source))
        with Image.open(source) as drawing:
            if drawing.mode != 'RGBA' or drawing.getchannel('A').getextrema() != (0, 255):
                raise ValueError(f'Walk source must have genuine alpha: {source.name}')
            for (actor, height), top, bottom in zip(actors, (0, row_split), (row_split, drawing.height), strict=True):
                frames = [
                    extract(drawing, (col * drawing.width // 4, top, (col + 1) * drawing.width // 4, bottom))
                    for col in range(4)
                ]
                scale = min(146 / max(frame.width for frame in frames), height / max(frame.height for frame in frames))
                for col, frame in enumerate(frames):
                    resized = frame.resize((round(frame.width * scale), round(frame.height * scale)), Image.Resampling.LANCZOS)
                    x = col * cell + (cell - resized.width) // 2
                    y = len(order) * cell + 155 - resized.height
                    atlas.alpha_composite(resized, (x, y))
                order.append(actor)
    file = DESTINATION / f'{journey}-stride-v6.webp'
    atlas.save(file, quality=84, method=6, exact=True)
    return dict(order=order, rows=actor_count, columns=4, cell=cell, sources=sources,
                asset=asset_description(file))


def pack_council_row(atlas, drawing, person, row, row_count, atlas_row, cell):
    top = row * drawing.height // row_count
    bottom = (row + 1) * drawing.height // row_count
    cell_width = drawing.width // 4
    # Cadfan's and Cadogan's raised hands reach across a nominal cell edge.
    overlap = 12 if person in {'cadfan', 'cadogan'} else 0
    frames = [
        extract(drawing, (col * cell_width - overlap, top, (col + 1) * cell_width + overlap, bottom), crop=False)
        for col in range(4)
    ]
    bounds = [frame.getchannel('A').getbbox() for frame in frames]
    left = min(box[0] for box in bounds)
    upper = min(box[1] for box in bounds)
    right = max(box[2] for box in bounds)
    lower = max(box[3] for box in bounds)
    # Use one crop for the whole row so heads, shoulders and the held hat stay aligned.
    scale = min(146 / (right - left), 148 / (lower - upper))
    size = (round((right - left) * scale), round((lower - upper) * scale))
    for col, frame in enumerate(frames):
        resized = frame.crop((left, upper, right, lower)).resize(size, Image.Resampling.LANCZOS)
        atlas.alpha_composite(resized, (col * cell + (cell - size[0]) // 2, atlas_row * cell + 155 - size[1]))


def prepare_council():
    name = 'heroldsrat-kammer-v6'
    original = SOURCE / f'{name}.png'
    with Image.open(original) as room:
        backgrounds = encode_scene_background(name, room.convert('RGB'), (1440, 720, 1120))
    sheets = [
        ('iestyn-gareth', ['iestyn', 'gareth']),
        ('trahern-cadogan', ['trahern', None]),
        ('cadogan-hut', ['cadogan']),
        ('cadfan', ['cadfan']),
        ('neala-branwen', ['neala', 'branwen']),
    ]
    cell = 160
    rows = sum(person is not None for _, people in sheets for person in people)
    atlas = Image.new('RGBA', (4 * cell, rows * cell))
    sources = []
    order = []
    for sheet_name, names in sheets:
        source = SOURCE / f'{sheet_name}-gesten-v6.png'
        sources.append(asset_description(source))
        with Image.open(source) as drawing:
            if drawing.mode != 'RGBA' or drawing.getchannel('A').getextrema() != (0, 255):
                raise ValueError(f'Council source must have genuine alpha: {source.name}')
            for row, person in enumerate(names):
                if person is None:
                    continue
                pack_council_row(atlas, drawing, person, row, len(names), len(order), cell)
                order.append(person)

    file = DESTINATION / 'heroldsrat-gesten-v6.webp'
    atlas.save(file, quality=84, method=6, exact=True)
    return dict(
        room=dict(source=asset_description(original), assets=backgrounds),
        atlas=dict(order=order, rows=rows, columns=4, cell=cell, sources=sources,
                   asset=asset_description(file))
    )


def prepare_journeys():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    groups = [
        ('owetas-quartett', 583, [
            ('oweta-lefraye', [('oweta', 145), ('lefraye', 145)], 443),
            ('rianna-caralyn', [('rianna', 143), ('caralyn', 143)], 443),
        ]),
        ('wolfshorn', 550, [
            ('duncan-gawain', [('duncan', 146), ('gawain', 145)], 443),
            ('ylva-freki', [('ylva', 145), ('freki', 106)], 478),
        ]),
        ('tiefenwyrm', 595, [
            ('idwal-trevor', [('idwal', 146), ('trevor', 143)], 443),
        ]),
    ]
    manifest = dict(version=6, groups={
        journey: dict(panorama=prepare_panorama(journey, ground_y), atlas=pack_journey_stride(journey, sheets))
        for journey, ground_y, sheets in groups
    }, council=prepare_council())
    (DESTINATION / 'journey-v6-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')
    print('Prepared 3 scrolling panoramas, 40 walk frames and the council with 28 gesture frames.')


