import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url), check = process.argv.includes('--check');
const sourcePath = 'modules/gwynthor-geography/gwynthor-section-layout.mjs';
const output = new URL('modules/gwynthor-geography/gwynthor-geography.global.js', root);
const receipt = new URL('modules/gwynthor-geography/build.generated.json', root);
const digest = data => createHash('sha256').update(data).digest('hex');
const sourceHash = digest(await readFile(new URL(sourcePath, root)));
if (check) {
  const saved = JSON.parse(await readFile(receipt, 'utf8'));
  if (saved.source !== sourceHash || saved.output !== digest(await readFile(output))) throw Error('Gwynthor-Kategorienbundle neu erzeugen.');
} else {
  const { build } = await import('esbuild');
  const result = await build({ entryPoints: [fileURLToPath(new URL(sourcePath, root))], bundle: true, format: 'iife',
    globalName: 'AleriaGwynthorGeography', write: false, target: 'es2022', legalComments: 'none' });
  const content = '// Generated by scripts/build-gwynthor-geography.mjs.\n' + result.outputFiles[0].text;
  await writeFile(output, content);
  await writeFile(receipt, JSON.stringify({ version: 1, source: sourceHash, output: digest(content) }, null, 2) + '\n');
}
console.log(`Gwynthor-Kategorien: ${check ? 'geprüft' : 'erzeugt'}.`);
