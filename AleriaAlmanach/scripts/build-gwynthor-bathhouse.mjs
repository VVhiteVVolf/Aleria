import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { buildGwynthorBathhouse, BATHHOUSE_SECTION } from '../modules/gwynthor-bathhouse/bathhouse-module.mjs';
import { HOUSE_FONTANI_FAMILY } from '../../Stammbäume/assets/js/data/house-fontani-family.js';

const entry = buildGwynthorBathhouse();
const directory = new URL('../../Charakter Archiv Exporte/Module/Badehaus Fontani/', import.meta.url);
const outputs = new Map([
  [new URL('../modules/gwynthor-bathhouse/bathhouse-data.js', import.meta.url),
    `// Generated by scripts/build-gwynthor-bathhouse.mjs. Local draft; not released.\n(() => {\n  const entry = ${JSON.stringify(entry, null, 2)};\n  const target = ${JSON.stringify(BATHHOUSE_SECTION)};\n  let section = SECTIONS.find(s => s.tab === target.tab && JSON.stringify(s.path || []) === JSON.stringify(target.path));\n  if (!section) { section = { ...target, entries: [] }; SECTIONS.push(section); }\n  if (!SECTIONS.some(s => s.entries?.some(e => e.id === entry.id))) section.entries.push(entry);\n})();\n`],
  [new URL('badehaus-fontani-2026-10-17.json', directory),
    JSON.stringify({ type: 'aleria-module-package', version: 1, exportedAt: '2026-10-17T00:00:00Z',
      module: { type: 'aleria-module', version: 1, section: BATHHOUSE_SECTION, entry } }, null, 2) + '\n'],
  [new URL('haus-fontani-2026-10-17.json', directory), JSON.stringify(HOUSE_FONTANI_FAMILY, null, 2) + '\n']
]);
for (const [url, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== content) throw new Error(`Veraltetes Badehaus-Paket: ${url}`);
  } else {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, content);
  }
}
console.log(JSON.stringify({ module: entry.id, pages: entry.pages.length, scenes: entry.pages.filter(p => p.sessionPage).length, familyMembers: HOUSE_FONTANI_FAMILY.persons.length, release: 'local-only' }));
