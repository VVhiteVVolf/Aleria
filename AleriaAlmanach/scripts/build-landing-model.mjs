import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const target = new URL('modules/landing/landing-model.global.js', root);
const result = await build({ entryPoints: [fileURLToPath(new URL('modules/landing/landing-classic-api.js', root))], bundle: true, format: 'iife', globalName: 'AleriaLandingModel', write: false, target: 'es2022', legalComments: 'none' });
const source = '// Generated by scripts/build-landing-model.mjs; edit the ES modules in modules/landing.\n' + result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw new Error('Das Landingpage-Modell muss neu erzeugt werden.');
} else await writeFile(target, source);
