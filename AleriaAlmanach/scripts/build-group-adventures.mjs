import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const target = new URL('modules/group-adventures/group-adventures.global.js', root);
const result = await build({ absWorkingDir: fileURLToPath(root), entryPoints: [fileURLToPath(new URL('modules/group-adventures/group-adventures-classic-api.mjs', root))],
  bundle: true, format: 'iife', globalName: 'AleriaGroupAdventures', write: false, target: 'es2022', legalComments: 'none' });
const source = '// Generated by scripts/build-group-adventures.mjs; edit the group feature modules.\n' + result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw Error('Die Gruppen-Abenteuerprojektion muss neu erzeugt werden.');
} else await writeFile(target, source);
