import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(frontend, '..');
const manifest = JSON.parse(await readFile(resolve(frontend, 'public/assets/house-armor/image-prompts.json'), 'utf8'));
const gallery = JSON.parse(await readFile(resolve(root, 'Gallerien/krieger/data/catalog.json'), 'utf8'));
const expected = gallery.houses.filter(house => house.location.includes('Celtigerns Wacht')).map(house => house.id).sort();
if (JSON.stringify(expected) !== JSON.stringify(manifest.houses.map(house => house.id).sort())) throw Error('Hausverzeichnis weicht von den Stammbäumen ab.');
const houses = [];
for (const house of manifest.houses) {
  if (house.generated) {
    if (!house.prompt) throw Error(`Prompt fehlt: ${house.id}`);
    const png = await readFile(resolve(frontend, 'public/assets/house-armor', house.regionId, house.file));
    if (png.subarray(1, 4).toString() !== 'PNG' || png[25] !== 6 || png.readUInt32BE(16) !== png.readUInt32BE(20)) throw Error(`Quadratisches RGBA-PNG erforderlich: ${house.id}`);
  }
  houses.push({ id: house.id, name: house.name, regionId: house.regionId, region: house.region, location: house.location, tree: house.tree,
    sourceIllustrationId: house.sourceIllustrationId, sourceImage: house.sourceImage,
    image: house.generated ? `/AleriaAlmanach/public/assets/house-armor/${house.regionId}/${house.file}` : '',
    status: house.generated ? 'ready' : house.sourceImage ? 'pending' : 'missing-reference' });
}
const output = `// Generated by scripts/build-house-armor.mjs.\nexport const HOUSE_ARMOR_HOUSES = ${JSON.stringify(houses, null, 2)};\n`;
const target = resolve(frontend, 'modules/house-armor/house-armor-catalog.js');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw Error('Hausrüstungskatalog ist veraltet.');
} else await writeFile(target, output);
console.log(`${houses.length} Häuser; ${houses.filter(house => house.image).length} Harnischbilder.`);
