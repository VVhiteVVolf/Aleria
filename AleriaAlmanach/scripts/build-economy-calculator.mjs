import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { readEconomyVenues, readEconomyCalendar, readEconomyModuleSources } from '../modules/economy-calculator/economy-source-venues.mjs';
import { buildEconomyExamples } from '../modules/economy-calculator/economy-examples.mjs';
import { calculateBusiness, demandCases, projectBusiness } from '../modules/economy-calculator/economy-engine.mjs';
import { HOUSEHOLD_PROFILES, calculateHousehold } from '../modules/economy-calculator/economy-households.mjs';
import { createPurchasingReference, calculatePurchasingPower } from '../modules/economy-calculator/economy-purchasing-power.mjs';
import { GWYNTHOR_ECONOMY, CENYR_WORK_CYCLE, ECONOMY_PRICE_LAYERS } from '../modules/economy-calculator/economy-world-context.mjs';
import { evaluateVenueScope } from '../modules/economy-calculator/economy-venue-scope.mjs';
import { buildVenueScenario } from '../modules/economy-calculator/economy-venue-scenario.mjs';
import { createServiceIncomeGuide } from '../modules/economy-calculator/economy-service-income.mjs';
const root = new URL('../', import.meta.url), check = process.argv.includes('--check');
const digest = content => createHash('sha256').update(content).digest('hex');
const calendar = await readEconomyCalendar(), examples = buildEconomyExamples(await readEconomyVenues(), calendar);
const sourceSections = await readEconomyModuleSources(), scope = [];
for (const section of sourceSections) for (const entry of section.entries) {
  const decision = evaluateVenueScope(entry, section);
  scope.push({ id: entry.id, title: entry.title, tab: section.tab, path: section.path, ...decision });
  if (decision.eligible && !examples.some(example => example.id === entry.id)) examples.push(buildVenueScenario(entry, section, calendar));
}
const catalogPath = new URL('modules/economy-calculator/economy-catalog.generated.mjs', root);
const catalog = '// Generated from the existing menus and personnel sources. Edit economy-examples.mjs.\nexport const ECONOMY_EXAMPLES = ' + JSON.stringify(examples, null, 2) + ';\n';
async function output(url, content) {
  if (check) { if (await readFile(url, 'utf8') !== content) throw Error(`Veraltete Wirtschaftskalkulation: ${fileURLToPath(url)}`); }
  else { await mkdir(new URL('.', url), { recursive: true }); await writeFile(url, content); }
}
await output(catalogPath, catalog);
const bundlePath = new URL('modules/economy-calculator/economy-runtime.global.js', root);
const receiptPath = new URL('modules/economy-calculator/economy-build.generated.json', root);
if (check) {
  // Production validates the checked-in bundle without installing a compiler
  // into the static site's root. Every bundled source and the output are sealed.
  const receipt = JSON.parse(await readFile(receiptPath, 'utf8'));
  for (const [input, expected] of Object.entries(receipt.inputs)) {
    if (input.includes('..') || !input.startsWith('modules/')) throw Error('Unzulässiger Pfad im Wirtschafts-Buildbeleg.');
    if (digest(await readFile(new URL(input, root))) !== expected) throw Error(`Wirtschaftsbundle neu erzeugen: ${input}`);
  }
  if (digest(await readFile(bundlePath)) !== receipt.output) throw Error('Wirtschaftsbundle stimmt nicht mit dem Buildbeleg überein.');
} else {
  const { build } = await import('esbuild');
  const bundle = await build({ absWorkingDir: fileURLToPath(root), entryPoints: ['modules/economy-calculator/economy-classic-api.mjs'], bundle: true,
    format: 'iife', globalName: 'AleriaEconomy', write: false, metafile: true, target: 'es2022', legalComments: 'none' });
  const content = '// Generated by scripts/build-economy-calculator.mjs; edit the feature ES modules.\n' + bundle.outputFiles[0].text;
  await output(bundlePath, content);
  const inputs = Object.fromEntries(await Promise.all(Object.keys(bundle.metafile.inputs).sort().map(async input => [input, digest(await readFile(new URL(input, root)))])));
  await output(receiptPath, JSON.stringify({ version: 1, inputs, output: digest(content) }, null, 2) + '\n');
}
const report = { type: 'aleria-economy-test-report', version: 1, date: '2026-10-19', inputMoneyUnit: 'Kupfertaler', ledgerMoneyUnit: 'Eisenpfennig', calendar,
  worldContext: GWYNTHOR_ECONOMY, priceLayers: ECONOMY_PRICE_LAYERS, socialWorkCycle: CENYR_WORK_CYCLE, purchasingReference: createPurchasingReference(),
  venueScope: scope,
  businesses: examples.map(scenario => ({ scenario, ordinary: calculateBusiness(scenario, calendar), demandCases: demandCases(scenario, calendar),
    purchasingPower: calculatePurchasingPower(calculateBusiness(scenario, calendar), createPurchasingReference()),
    month: projectBusiness(scenario, calendar, calendar.daysPerMonth / calendar.daysPerWeek), year: projectBusiness(scenario, calendar, calendar.daysPerYear / calendar.daysPerWeek) })),
  households: HOUSEHOLD_PROFILES.map(profile => ({ profile, calculation: calculateHousehold(profile, calendar) })),
  serviceIncome: createServiceIncomeGuide(calendar) };
await output(new URL('docs/economy/venue-calculations-2026-10-19.json', root), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ businesses: report.businesses.map(({ scenario, ordinary }) => ({ title: scenario.title, people: ordinary.activeCount, revenueWeekKT: ordinary.totals.gross / 100, freeCashWeekKT: ordinary.totals.freeCash / 100 })), householdProfiles: HOUSEHOLD_PROFILES.length }));
