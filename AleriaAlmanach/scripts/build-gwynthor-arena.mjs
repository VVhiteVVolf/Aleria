import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { buildGwynthorArena, ARENA_SECTION } from '../modules/gwynthor-arena/arena-module.mjs';

const entry = buildGwynthorArena();
const directory = new URL('../../Charakter Archiv Exporte/Module/Kampfarena Gwynthor/', import.meta.url);
const outputs = new Map([
  [new URL('../modules/gwynthor-arena/arena-data.js', import.meta.url),
    `// Generated by scripts/build-gwynthor-arena.mjs. Local draft; not released.\n(() => {\n  const entry = ${JSON.stringify(entry, null, 2)};\n  const target = ${JSON.stringify(ARENA_SECTION)};\n  let section = SECTIONS.find(s => s.tab === target.tab && JSON.stringify(s.path || []) === JSON.stringify(target.path));\n  if (!section) { section = { ...target, entries: [] }; SECTIONS.push(section); }\n  if (!SECTIONS.some(s => s.entries?.some(e => e.id === entry.id))) section.entries.push(entry);\n})();\n`],
  [new URL('kampfarena-gwynthor-2026-10-17.json', directory),
    JSON.stringify({ type: 'aleria-module-package', version: 1, exportedAt: '2026-10-17T00:00:00Z',
      module: { type: 'aleria-module', version: 1, section: ARENA_SECTION, entry } }, null, 2) + '\n']
]);

for (const [url, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== content) throw new Error(`Veraltetes Arena-Paket: ${url}`);
  } else {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, content);
  }
}
console.log(JSON.stringify({ module: entry.id, contentPages: entry.pages.length, scenes: 3, release: 'local-only' }));
