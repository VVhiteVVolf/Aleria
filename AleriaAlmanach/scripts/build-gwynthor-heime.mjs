import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { buildGwynthorHomes, HOMES_SECTION } from '../modules/gwynthor-heime/homes-module.mjs';
import { renderArchiveSectionRegistration } from '../modules/archive/archive-section-registration.mjs';
import { GWYNTHOR_AREA_ICONS } from '../modules/gwynthor-geography/gwynthor-section-layout.mjs';
import { projectHouseholdWorkplaces, HOUSEHOLD_WORKPLACE_LINKS } from '../modules/gwynthor-heime/household-workplaces.mjs';
const entries = buildGwynthorHomes();
const outputs = new Map([[new URL('../modules/gwynthor-heime/homes-data.js', import.meta.url), renderArchiveSectionRegistration('registerGwynthorHomes', entries.map(entry => ({
  tab: HOMES_SECTION.tab, path: HOMES_SECTION.path, description: HOMES_SECTION.desc, icon: GWYNTHOR_AREA_ICONS['Gwynthor-Stadt'], entry
})), 'scripts/build-gwynthor-heime.mjs')]]);
outputs.set(new URL('../modules/gwynthor-heime/household-workplaces.js', import.meta.url),
  '// Generated by scripts/build-gwynthor-heime.mjs; feature-owned read projection.\nfunction migrateHouseholdWorkplaceEntry(entry) {\n' +
  `  return (${projectHouseholdWorkplaces.toString()})(entry, ${JSON.stringify(HOUSEHOLD_WORKPLACE_LINKS)});\n}\n`);
for (const entry of entries) outputs.set(new URL(`../../Charakter Archiv Exporte/Module/Gwynthorer Heime/${entry.id}-2026-10-20.json`, import.meta.url), JSON.stringify({
  type: 'aleria-module-package', version: 1, exportedAt: '2026-10-20T00:00:00Z', module: { type: 'aleria-module', version: 1, section: HOMES_SECTION, entry }
}, null, 2) + '\n');
for (const [url, content] of outputs) {
  if (process.argv.includes('--check')) { if (await readFile(url, 'utf8') !== content) throw Error(`Veraltetes Wohnhaus-Modul: ${url}`); }
  else { await mkdir(new URL('.', url), { recursive: true }); await writeFile(url, content); }
}
console.log(JSON.stringify({ modules: entries.map(e => ({ title: e.title, pages: e.pages.length })), shops: false, deployed: false }));
