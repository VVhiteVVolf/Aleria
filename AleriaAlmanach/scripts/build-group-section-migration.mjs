import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const almanachRoot = fileURLToPath(new URL('../', import.meta.url));
// Netlify validates the committed browser bundle without installing this
// nested package automatically. Use its lockfile, as the chart release does.
if (process.argv.includes('--prepare')) {
  const args = ['ci', '--include=dev', '--ignore-scripts', '--no-audit', '--no-fund'];
  const result = process.platform === 'win32'
    ? spawnSync(process.env.ComSpec || 'cmd.exe', ['/d', '/s', '/c', `npm ${args.join(' ')}`], { cwd: almanachRoot, stdio: 'inherit' })
    : spawnSync('npm', args, { cwd: almanachRoot, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`Almanach build dependency installation failed (${result.status ?? result.signal}).`);
}
const { build } = await import('esbuild');

const feature = new URL('../modules/module-store/', import.meta.url);
const target = new URL('group-section-migration.global.js', feature);
const result = await build({ entryPoints: [fileURLToPath(new URL('group-section-migration.js', feature))],
  absWorkingDir: almanachRoot,
  bundle: true, format: 'iife', globalName: 'AleriaGroupSectionMigration', write: false,
  target: 'es2022', legalComments: 'none' });
const source = '// Generated by scripts/build-group-section-migration.mjs; edit group-section-migration.js.\n' + result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw new Error('Die Gruppen-Kategoriekorrektur muss neu erzeugt werden.');
} else await writeFile(target, source);
