import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('public/assets/character-equipment/image-prompts.json', root), 'utf8'));
const keys = new Set();
const identities = new Map();
for (const entry of manifest.entries) {
  if (keys.has(entry.key)) throw new Error(`Duplicate artwork key: ${entry.key}`);
  keys.add(entry.key);
  if (!/^[a-z0-9-]+-v\d+\.png$/.test(entry.file)) throw new Error(`Invalid artwork filename: ${entry.file}`);
  const png = await readFile(new URL(`public/assets/character-equipment/${entry.file}`, root));
  if (png.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a'
    || png.readUInt32BE(16) !== png.readUInt32BE(20) || png[25] !== 6) {
    throw new Error(`Artwork must be a square RGBA PNG: ${entry.file}`);
  }
  for (const binding of entry.bindings) {
    for (const id of [...binding.itemIds, ...binding.combatEntryIds]) {
      const identity = `${binding.characterId}:${id}`;
      if (identities.has(identity) && identities.get(identity) !== entry.key) throw new Error(`Ambiguous artwork binding: ${identity}`);
      identities.set(identity, entry.key);
    }
  }
}
const entries = manifest.entries.map(({ key, file, bindings, legacyImages }) => ({
  key, image: `/AleriaAlmanach/public/assets/character-equipment/${file}`, bindings, legacyImages
}));
const target = new URL('modules/character-equipment/equipment-artwork-catalog.js', root);
const source = `// Generated by scripts/build-equipment-artwork.mjs. Edit image-prompts.json.\nexport const EQUIPMENT_ARTWORK = ${JSON.stringify(entries, null, 2)};\n`;
const escape = value => String(value || '').replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const owners = [...new Set(manifest.entries.map(entry => entry.owner))];
const gallery = `<!doctype html>
<html lang="de"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Aleria · Waffen &amp; Rüstungen</title><link rel="stylesheet" href="gallery.css?v=20260928"></head>
<body><header><p>ALERIA · AUSRÜSTUNG</p><h1>Waffen &amp; Rüstungen</h1><p>${entries.length} Illustrationen · quadratische PNGs mit transparentem Hintergrund</p><label><input type="checkbox" id="light"> Heller Bildhintergrund</label></header>
<main>${owners.map(owner => `<section><h2>${escape(owner)}</h2><div class="items">${manifest.entries.filter(entry => entry.owner === owner).map(entry => `<figure><a href="${entry.file}" download><img src="${entry.file}" alt="${escape(entry.title)}" width="1254" height="1254" loading="lazy"></a><figcaption>${escape(entry.title)}${entry.key === 'draig-dolch' ? '<small>Gawain und Gildas</small>' : ''}</figcaption></figure>`).join('\n')}</div></section>`).join('\n')}</main>
<footer><a href="image-prompts.json">Bildprompts und Zuordnungen</a> · Erstellt mit der integrierten Bildgenerierung.</footer></body></html>\n`;
for (const [url, content] of [[target, source], [new URL('public/assets/character-equipment/index.html', root), gallery]]) {
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== content) throw new Error(`Equipment artwork output is outdated: ${fileURLToPath(url)}`);
  } else await writeFile(url, content);
}
console.log(`${entries.length} equipment illustrations: ${fileURLToPath(target)}`);
