import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { buildOwetaQuartet, OWETA_QUARTET_SECTION } from '../modules/oweta-quartett/oweta-quartett-module.mjs';
import { OWETA_QUARTET_STARTER_STOCK } from '../modules/oweta-quartett/oweta-quartett-data.mjs';

const entry = buildOwetaQuartet();
const directory = new URL('../../Charakter Archiv Exporte/Module/Owetas Quartett/', import.meta.url);
const outputs = new Map([
  [new URL('../modules/oweta-quartett/oweta-quartett-data.js', import.meta.url),
    `// Generated by scripts/build-oweta-quartett.mjs.\n(() => {\n  const entry = ${JSON.stringify(entry, null, 2)};\n  const target = ${JSON.stringify(OWETA_QUARTET_SECTION)};\n  let section = SECTIONS.find(s => s.tab === target.tab && JSON.stringify(s.path || []) === JSON.stringify(target.path));\n  if (!section) { section = { ...target, entries: [] }; SECTIONS.push(section); }\n  if (!SECTIONS.some(s => s.entries?.some(e => e.id === entry.id))) section.entries.push(entry);\n})();\n`],
  [new URL('owetas-quartett-2026-11-03.json', directory), JSON.stringify({ type: 'aleria-module', version: 2,
    section: OWETA_QUARTET_SECTION, entry }, null, 2) + '\n'],
  [new URL('startvorrat-2026-11-03.json', directory), JSON.stringify({ schemaVersion: 1, groupId: entry.id,
    note: 'Einmalige Startausstattung des gemeinsamen Gruppeninventars; keine persönlichen Inventare oder Live-Ressourcen ändern.',
    stock: OWETA_QUARTET_STARTER_STOCK }, null, 2) + '\n']
]);
for (const [url, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== content) throw new Error(`Veraltete Quartett-Datei: ${url}`);
  } else {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, content);
  }
}
console.log(JSON.stringify({ module: entry.id, pages: entry.pages.length, members: 4, companions: 6, starterStock: OWETA_QUARTET_STARTER_STOCK.length }));
