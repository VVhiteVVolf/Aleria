import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { completeLachendeNixe } from '../modules/lachende-nixe/nixe-module.mjs';

const read = async path => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const source = (await read('../modules/lachende-nixe/sources/module-before-finalization.json')).entry;
const teyrngarch = await read('../modules/krumme-kanne/source/teyrngarch.json');
const imports = await read('../modules/lachende-nixe/sources/drink-catalogs.json');
const catalogs = [teyrngarch.entry || teyrngarch, ...imports.map(item => item.entry || item)];
const entry = completeLachendeNixe(source, catalogs);
const section = { key: 'Gwynthor', tab: 'Völker & Kulturen', desc: '',
  nodeId: 'node:volker-kulturen:cenyr/celtigerns-wacht/llamreis-ankunft/gwynthor',
  path: ['Cenyr', 'Celtigerns Wacht', 'Llamreis Ankunft', 'Gwynthor'] };
const directory = new URL('../../Charakter Archiv Exporte/Module/Lachende Nixe/', import.meta.url);
await mkdir(directory, { recursive: true });
const outputs = new Map([
  [new URL('../modules/lachende-nixe/nixe-data.js', import.meta.url), `// Generated by scripts/build-lachende-nixe.mjs.\n(() => {\n  const entry = ${JSON.stringify(entry, null, 2)};\n  const target = ${JSON.stringify(section)};\n  let section = SECTIONS.find(s => s.tab === target.tab && JSON.stringify(s.path || []) === JSON.stringify(target.path));\n  if (!section) { section = { ...target, entries: [] }; SECTIONS.push(section); }\n  if (!SECTIONS.some(s => s.entries?.some(e => e.id === entry.id))) section.entries.push(entry);\n})();\n`],
  [new URL('lachende-nixe-2026-10-16.json', directory), JSON.stringify({ type: 'aleria-module-package', version: 1,
    exportedAt: '2026-10-16T12:00:00Z', module: { type: 'aleria-module', version: 1, section, entry } }, null, 2) + '\n']
]);
for (const [url, text] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== text) throw new Error(`Veraltetes Nixe-Paket: ${url}`);
  } else await writeFile(url, text);
}
console.log(`Die Lachende Nixe: ${entry.pages.length} Seiten, ${entry.pages[2].hierarchy.trees.length} Reiter, ${entry.pages[3].tradeCatalog.items.length} Waren, ${entry.pages[4].guildServices.services.length} Services, ${entry.pages[5].guestRegister.sections.flatMap(section => section.guests).length} Gästeplätze.`);
