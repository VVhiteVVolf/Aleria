import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { FAMILY_REGISTRY } from '../../Stammbäume/assets/js/data/families.registry.js';
import { createFamilyCandidates } from '../modules/character-genealogy/genealogy-mapping.js';
import { importAuthoredCharacters } from '../../CharakterDatenbank/scripts/import-authored-characters.mjs';
import { PERLLAN_CHARACTER_FEATURE, buildPerllanCharacterExports } from '../modules/perllan/character-content.mjs';

export async function buildPerllanCharacters({ check = false } = {}) {
  const root = new URL('../../', import.meta.url);
  const record = FAMILY_REGISTRY.find(record => record.id === 'perllan');
  const exports = buildPerllanCharacterExports(record);
  if (exports.length !== 27) throw Error('Der geprüfte Perllan-Import erwartet genau 27 benannte Personen.');
  const biographies = Object.fromEntries(exports.map(entry => [entry.source.personId, entry.character.biography]));
  const outputs = [
    ['Stammbäume/assets/js/data/perllan-person-biographies.generated.js',
      '// Generated by AleriaAlmanach/scripts/build-perllan-characters.mjs.\n'
      + `export const PERLLAN_PERSON_BIOGRAPHIES = Object.freeze(${JSON.stringify(biographies, null, 2)});\n`],
    ...exports.map(entry => [entry.sourcePath, JSON.stringify(entry, null, 2) + '\n'])
  ];
  for (const [path, text] of outputs) {
    const url = new URL(path, root);
    if (check) {
      if (await readFile(url, 'utf8') !== text) throw Error(`Veraltete Perllan-Figurenquelle: ${path}`);
    } else {
      await mkdir(new URL('.', url), { recursive: true });
      await writeFile(url, text);
    }
  }
  return importAuthoredCharacters({ sources: exports.map(entry => entry.sourcePath),
    feature: PERLLAN_CHARACTER_FEATURE, familyCandidates: createFamilyCandidates(record), check });
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  console.log(JSON.stringify(await buildPerllanCharacters({ check: process.argv.includes('--check') })));
}
