import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const target = new URL('modules/currency/currency-art.global.js', root);
const result = await build({ absWorkingDir:fileURLToPath(root),
  entryPoints:[fileURLToPath(new URL('modules/currency/currency-art-classic-api.mjs',root))],
  bundle:true,format:'iife',globalName:'AleriaCurrencyArt',write:false,target:'es2022',legalComments:'none' });
const source = '// Generated by scripts/build-currency-art.mjs; edit modules/currency/currency-art.js.\n' + result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(target,'utf8') !== source) throw Error('Die gemeinsame Münzbild-Fassade muss neu erzeugt werden.');
} else await writeFile(target,source);
