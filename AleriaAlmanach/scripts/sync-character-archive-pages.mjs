import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';

// These two local pages own the lore. The archive consumes a reproducible snapshot,
// without fetching entire HTML pages or interpreting market prose in the browser.
const root = new URL('../../', import.meta.url);
const target = new URL('../modules/character-archive/character-archive-page-data.js', import.meta.url);
const decode = value => String(value || '').replace(/&amp;/g, '&').replace(/&quot;/g, '"')
  .replace(/&#39;|&apos;/g, "'").replace(/&nbsp;/g, ' ').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const text = value => decode(String(value || '').replace(/<[^>]*>/g, ' ')).replace(/\s+/g, ' ').trim();
const attr = (html, name) => decode(html.match(new RegExp(`\\b${name}="([^"]*)"`))?.[1] || '');
const slug = value => value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/ß/g, 'ss').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const [classHtml, horseHtml] = await Promise.all([
  readFile(new URL('Klassenordner/Klassenseite.html', root), 'utf8'),
  readFile(new URL('Markt/Rossmarkt/Rossmarkt.html', root), 'utf8')
]);

const classes = new Map();
function collectClasses(html, culture = '') {
  for (const match of html.matchAll(/<a\b[^>]*class="class-card\b[^>]*>([\s\S]*?)<\/a>/g)) {
    const name = text(match[1].match(/class="class-name">([^<]+)/)?.[1]);
    if (!name || name === 'Unterklasse') continue;
    const existing = classes.get(name);
    if (existing) {
      if (culture && !existing.cultures.includes(culture)) existing.cultures.push(culture);
      continue;
    }
    classes.set(name, {
      id: slug(name), name, baseClass: !culture, cultures: culture ? [culture] : [],
      order: classes.size, description: attr(match[0], 'data-tooltip'),
      icon: attr(match[1].match(/<img\b[^>]*>/)?.[0] || '', 'src'),
      sourcePage: 'Klassenordner/Klassenseite.html'
    });
  }
}
collectClasses(classHtml.slice(classHtml.indexOf('<!-- BASISKLASSEN -->'), classHtml.indexOf('<!-- LÄNDERPFADE -->')));
for (const section of classHtml.matchAll(/<section\b[^>]*class="land-section\b[^>]*>([\s\S]*?)<\/section>/g)) {
  const culture = text(section[1].match(/<h2[^>]*>([\s\S]*?)<\/h2>/)?.[1]);
  assert(culture, 'Kulturüberschrift fehlt');
  collectClasses(section[1], culture);
}
assert.equal([...classes.values()].filter(entry => entry.baseClass).length, 15, 'Basisklassen-Struktur hat sich geändert');
assert(classes.size > 80, 'Kulturklassen konnten nicht vollständig gelesen werden');

const horses = [];
for (const match of horseHtml.matchAll(/<tr\b[^>]*class="horse-row"[^>]*>([\s\S]*?)<\/tr>/g)) {
  const html = match[0];
  const image = html.match(/<img\b[^>]*class="horse-img"[^>]*>/)?.[0] || '';
  const section = attr(html, 'data-section');
  horses.push({
    id: attr(html, 'data-name'), name: attr(image, 'alt'), section,
    type: ({ roesser: 'Pferderasse', ponys: 'Ponyrasse', uebrige: 'Weiteres Reittier' })[section] || section,
    region: attr(html, 'data-region'),
    origin: text(html.match(/class="origin-val">([\s\S]*?)<\/div>/)?.[1]),
    description: text(html.match(/class="horse-desc">([\s\S]*?)<\/span>/)?.[1]),
    image: attr(image, 'src'),
    price: text(html.match(/class="price-text">([\s\S]*?)<\/div>/)?.[1]),
    currency: text(html.match(/class="price-currency">([\s\S]*?)<\/div>/)?.[1]),
    uses: [...html.matchAll(/class="use-tag\b[^"]*">([\s\S]*?)<\/span>/g)].map(item => text(item[1])),
    sourcePage: 'Markt/Rossmarkt/Rossmarkt.html'
  });
}
assert(horses.length >= 30 && horses.every(entry => entry.id && entry.name && entry.description && entry.origin), 'Rossmarkt-Zeilen sind unvollständig');
assert.equal(new Set(horses.map(entry => entry.id)).size, horses.length, 'Doppelte Rossmarkt-ID');
assert.equal(horses.find(entry => entry.id === 'rhyfel')?.section, 'roesser');
const output = `// Generated by scripts/sync-character-archive-pages.mjs; edit the source pages, then sync.\nexport const ARCHIVE_PAGE_CLASSES = Object.freeze(${JSON.stringify([...classes.values()], null, 2)});\n\nexport const ARCHIVE_PAGE_MOUNTS = Object.freeze(${JSON.stringify(horses, null, 2)});\n`;
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), output, 'Archivseiten-Snapshot veraltet: node scripts/sync-character-archive-pages.mjs');
else await writeFile(target, output, 'utf8');
console.log(`Archivseiten: ${classes.size} Klassen, ${horses.length} Rossmarkt-Einträge${process.argv.includes('--check') ? ' geprüft' : ' synchronisiert'}.`);
