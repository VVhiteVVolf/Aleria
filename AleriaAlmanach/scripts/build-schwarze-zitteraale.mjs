import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { buildZitteraaleModule } from '../modules/schwarze-zitteraale/zitteraale-module.mjs';
import { buildZitteraaleGroupModules, ZITTERAALE_SECTION_PATH, ZITTERAALE_GROUP_SECTION_PATH } from '../modules/schwarze-zitteraale/zitteraale-group-modules.mjs';
import { buildMedrawdCharacterExport } from '../modules/schwarze-zitteraale/medrawd-angau.mjs';
import { buildCadwganCharacterExport } from '../modules/schwarze-zitteraale/sumpfnattern-biography.mjs';
import { projectZitteraaleCharacterUpdates, ZITTERAALE_AUTHORED_AT } from '../modules/schwarze-zitteraale/zitteraale-character-updates.mjs';
import { ZITTERAALE_LEADERS } from '../modules/schwarze-zitteraale/zitteraale-people.mjs';
import { upgradeZitteraaleEntry } from '../modules/schwarze-zitteraale/zitteraale-migration.mjs';
import { renderArchiveSectionRegistration } from '../modules/archive/archive-section-registration.mjs';
import { importAuthoredCharacters } from '../../CharakterDatenbank/scripts/import-authored-characters.mjs';

const root = new URL('../../', import.meta.url);
const check = process.argv.includes('--check');
const inputs = new Map();
async function readJson(file) {
  const text = await readFile(new URL(file, root), 'utf8');
  inputs.set(file, text);
  return JSON.parse(text);
}
const entry = buildZitteraaleModule();
const groups = buildZitteraaleGroupModules();
const registration = [
  { tab: 'Kriminalität', path: ZITTERAALE_SECTION_PATH, entryId: entry.id },
  ...groups.map(group => ({ tab: 'Kriminalität', path: ZITTERAALE_GROUP_SECTION_PATH, entry: group }))
];
const content = `// Generated by scripts/build-schwarze-zitteraale.mjs. Edit the feature models.
const ZITTERAALE_CANONICAL_ENTRY = ${JSON.stringify(entry, null, 2)};
function migrateZitteraaleEntry(entry) { return (${upgradeZitteraaleEntry.toString()})(entry, ZITTERAALE_CANONICAL_ENTRY); }
(function registerZitteraaleModule() {
  const section = SECTIONS.find(section => section.entries?.some(entry => entry.id === ZITTERAALE_CANONICAL_ENTRY.id))
    || SECTIONS.find(section => section.key === 'Kriminalität');
  if (!section) throw new Error('Kriminalitätsbereich fehlt.');
  const index = section.entries.findIndex(entry => entry.id === ZITTERAALE_CANONICAL_ENTRY.id);
  if (index < 0) section.entries.push(structuredClone(ZITTERAALE_CANONICAL_ENTRY));
  else section.entries[index] = migrateZitteraaleEntry(section.entries[index]);
})();
${renderArchiveSectionRegistration('registerZitteraaleSections', registration, 'scripts/build-schwarze-zitteraale.mjs')}`;
const outputs = new Map([['AleriaAlmanach/modules/schwarze-zitteraale/zitteraale-data.js', content]]);
for (const module of [entry, ...groups]) {
  const sectionPath = module.id === entry.id ? ZITTERAALE_SECTION_PATH : ZITTERAALE_GROUP_SECTION_PATH;
  outputs.set(`Charakter Archiv Exporte/Module/Schwarze Zitteraale/${module.id}-2026-11-16.json`, JSON.stringify({
    type: 'aleria-module-package', version: 1, exportedAt: ZITTERAALE_AUTHORED_AT,
    module: { type: 'aleria-module', version: 1, section: { key: sectionPath.at(-1), tab: 'Kriminalität', path: sectionPath }, entry: module }
  }, null, 2) + '\n');
}

const registry = await readJson('CharakterDatenbank/registry.json');
const snapshot = await readJson('CharakterDatenbank/generated/characters.snapshot.json');
const report = await readJson('CharakterDatenbank/generated/sync-report.json');
const selected = new Set(ZITTERAALE_LEADERS.slice(1).map(person => person.characterId));
const records = await Promise.all(registry.records.filter(row => selected.has(row.firestoreDocumentId))
  .map(row => readJson(`CharakterDatenbank/${row.path}`)));
const updated = projectZitteraaleCharacterUpdates({ registry, snapshot, report, records });
for (const item of updated.records) outputs.set(`CharakterDatenbank/${item.path}`, JSON.stringify(item.record, null, 2) + '\n');
for (const [file, data] of [
  ['registry.json', updated.registry], ['generated/characters.snapshot.json', updated.snapshot], ['generated/sync-report.json', updated.report]
]) outputs.set(`CharakterDatenbank/${file}`, JSON.stringify(data, null, 2) + '\n');
for (const exported of updated.exports) outputs.set(exported.sourcePath, JSON.stringify(exported, null, 2) + '\n');
const medrawd = buildMedrawdCharacterExport();
const medrawdPath = 'Charakter Archiv Exporte/Schwarze Zitteraale/medrawd-angau-2026-11-16.json';
outputs.set(medrawdPath, JSON.stringify(medrawd, null, 2) + '\n');
const cadwganPath = 'Charakter Archiv Exporte/Schwarze Zitteraale/cadwgan-bwch-2026-11-22.json';
outputs.set(cadwganPath, JSON.stringify(buildCadwganCharacterExport(), null, 2) + '\n');

if (!check) for (const [file, before] of inputs) {
  if (await readFile(new URL(file, root), 'utf8') !== before) throw Error(`Geänderte Quelle während des Builds: ${file}`);
}
for (const [file, text] of outputs) {
  const target = new URL(file, root);
  if (check) {
    if (await readFile(target, 'utf8') !== text) throw Error(`Veraltete Zitteraal-Ausgabe: ${file}`);
  } else {
    await mkdir(new URL('.', target), { recursive: true });
    await writeFile(target, text);
  }
}
const imported = await importAuthoredCharacters({ feature: 'schwarze-zitteraale', check, sources: [medrawdPath, cadwganPath] });
console.log(JSON.stringify({ module: entry.id, pages: entry.pages.length, groupModules: groups.length,
  groupPages: groups.reduce((sum, group) => sum + group.pages.length, 0), renamedPeople: selected.size, imported }));
