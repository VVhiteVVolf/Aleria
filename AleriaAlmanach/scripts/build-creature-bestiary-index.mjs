import { readdir, readFile, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { HORSE_BREEDING_LORE_CROSSINGS } from '../../Bestiarium/modules/horse-breeding/horse-breeding-registry.mjs';
import { horseCrossingAnchor } from '../../Bestiarium/modules/horse-breeding/horse-breeding-model.mjs';

const root = fileURLToPath(new URL('../../Bestiarium/', import.meta.url));
const destination = new URL('../modules/creatures/catalog/bestiary-profile-index.js', import.meta.url);
const genera = { pferde: 'Pferde', hunde: 'Hunde', katzen: 'Katzen', woelfe: 'Wölfe', baeren: 'Bären', trolle: 'Trolle' };

async function collectProfiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const profiles = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) profiles.push(...await collectProfiles(absolute));
    else if (entry.name === 'profil.json') {
      const id = path.relative(root, directory).split(path.sep).join('/');
      // Group essays describe categories, not an individual species or breed.
      if (id.startsWith('wesen/gruppen/')) continue;
      const profile = JSON.parse(await readFile(absolute, 'utf8'));
      const name = profile.name || profile.title;
      if (!name) throw new Error(`Bestiarium-Profil ohne Namen: ${id}`);
      await access(path.join(directory, 'index.html'));
      profiles.push({ id, name, genus: id.split('/').map(part => genera[part]).find(Boolean) || '' });
    }
  }
  return profiles;
}

const profiles = await collectProfiles(root);
const breedingPage = await readFile(path.join(root, 'tiere/pferde/zuchtbuch/index.html'), 'utf8');
for (const crossing of HORSE_BREEDING_LORE_CROSSINGS.filter(entry => entry.bestiaryId)) {
  if (!/^[a-z0-9-]+$/.test(crossing.bestiaryId)) throw new Error(`Ungültige Bestiarium-ID der Zucht: ${crossing.name}`);
  const anchor = horseCrossingAnchor(crossing.mareId, crossing.sireId);
  if (!breedingPage.includes(`id="${anchor}"`)) throw new Error('Zuchtbuch zuerst mit node Bestiarium/scripts/build-horse-breeding.mjs aktualisieren.');
  profiles.push({ id: `tiere/pferde/zuchtbuch/${crossing.bestiaryId}`, name: crossing.name, genus: 'Pferde',
    url: `/Bestiarium/tiere/pferde/zuchtbuch/index.html#${anchor}` });
}
profiles.sort((a, b) => a.id.localeCompare(b.id, 'en'));
const output = '// Generated by scripts/build-creature-bestiary-index.mjs from actual Bestiarium profiles.\n'
  + 'export const BESTIARY_PROFILES = Object.freeze([\n'
  + profiles.map(profile => `  Object.freeze(${JSON.stringify(profile)}),`).join('\n') + '\n]);\n';
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('Bestiarium-Index ist veraltet. npm run build:creature-bestiary ausführen.');
} else await writeFile(destination, output);
console.log(`Bestiarium-Index: ${profiles.length} Arten-, Rasse- und Zuchtbucheinträge geprüft.`);
