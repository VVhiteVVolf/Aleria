import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { getDraigGardeEntry } from '../modules/draig-leibgarde/draig-leibgarde-entry.mjs';

const target = new URL('../modules/draig-leibgarde/draig-leibgarde-data.js', import.meta.url);
const entry = JSON.stringify(getDraigGardeEntry(), null, 2).split('\n').map(line => `  ${line}`).join('\n').trimStart();
const expected = `// Generated by scripts/build-draig-garde-module.mjs from the pure entry source.
// The existing classic registration and load order remain unchanged.
(function registerDraigLeibgarde() {
  const id = 'draig-leibgarde';
  if (SECTIONS.some(section => section.entries?.some(entry => entry.id === id))) return;
  const entry = ${entry};
  const tab = 'Gruppen';
  const path = ['Cenyr', 'Celtigerns Wacht', 'Haus Draig'];
  let section = SECTIONS.find(candidate => candidate.tab === tab
    && candidate.path?.length === path.length
    && path.every((part, index) => candidate.path[index] === part));
  if (!section) {
    section = {
      key: path[path.length - 1], tab, path,
      iconUrl: '../IconOrdner/ReiterIcons/Weltpfade/gruppen.png',
      desc: 'Die Gemeinschaften und bewaffneten Dienste des Hauses Draig.',
      entries: []
    };
    SECTIONS.push(section);
  }
  section.entries.push(entry);
})();
`;

if (process.argv.includes('--write')) {
  await writeFile(target, expected);
  console.log('PASS: Draig-Garde-Modul aus der zuständigen Quelle erzeugt.');
} else {
  assert.equal(await readFile(target, 'utf8'), expected, 'Draig-Garde-Seed ist veraltet; gezielt --write ausführen.');
  console.log('PASS: Draig-Garde-Modul entspricht seiner Quelle.');
}
