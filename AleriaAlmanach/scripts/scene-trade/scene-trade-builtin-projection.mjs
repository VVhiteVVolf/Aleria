import assert from 'node:assert/strict';
import { buildModuleOffers, isShopModule } from '../../modules/item-register/item-register-module-catalog.js';
import { STANDARD_ITEMS } from '../../modules/item-register/item-register-standard.js';

const copy = value => structuredClone(value);
const pick = (source, keys) => Object.fromEntries(keys.filter(key => source?.[key] !== undefined).map(key => [key, copy(source[key])]));

export function projectBuiltinTradeModule(entry, section) {
  const projected = pick(entry, ['id', 'title', 'type', 'category', 'hidden', 'archived', 'isTemplate',
    'portrait', 'image', 'symbol', 'economyPriceReview']);
  // Keep the original array positions: page indexes form offer source identity
  // and are the fallback session thread key. Unrelated prose becomes {}.
  projected.pages = (entry.pages || []).map((page, index) => {
    if (!page?.sessionPage && !page?.tradeCatalogPage && !page?.goodsTablePage) return index === 0 && page?.image ? { image: page.image } : {};
    return pick(page, ['id', 'pageTitle', 'title', 'image', 'sessionPage', 'commentThreadKey', 'sessionStatus',
      'sessionDateAleria', 'sessionTime', 'sessionLocation', 'goodsTablePage', 'goodsTable', 'tradeCatalogPage', 'tradeCatalog']);
  });
  return { entry: projected, section: pick(section, ['id', 'key', 'tab', 'title', 'path', 'nodeId']) };
}

export function projectBuiltinTradeModules(sections, { isPublicSection, standards = STANDARD_ITEMS } = {}) {
  assert.equal(typeof isPublicSection, 'function', 'The canonical section privacy policy is required.');
  const seen = new Set(), result = [];
  for (const section of sections) {
    for (const entry of section.entries || []) {
      if (!entry?.id || seen.has(entry.id)) continue;
      seen.add(entry.id); // Same first-builtin identity precedence as getAllSections.
      if (!isPublicSection(section) || section.hidden === true || section.archived === true || section.isTemplate === true
        || !isShopModule(entry) || entry.title === '[PLATZHALTER]'
        || !(entry.pages || []).some(page => page?.sessionPage || page?.tradeCatalogPage || page?.goodsTablePage)) continue;
      const projected = projectBuiltinTradeModule(entry, section);
      // Existing business normalization is the authority. A new consumed field
      // must fail here instead of silently changing quote/definition identities.
      assert.deepEqual(buildModuleOffers([projected.entry], standards), buildModuleOffers([entry], standards),
        `Builtin projection changes merchant offers: ${entry.id}`);
      result.push(projected);
    }
  }
  return result.sort((first, second) => first.entry.id.localeCompare(second.entry.id, 'en'));
}

export function builtinTradeSource(modules, { inputDigest, sourceFiles }) {
  return '// Generated by AleriaAlmanach/scripts/build-scene-trade-builtins.mjs from committed public browser sources.\n'
    + '// Do not author prices, page identities or biography content here.\n'
    + `export const BUILTIN_TRADE_INPUT_DIGEST = ${JSON.stringify(inputDigest)};\n`
    + `export const BUILTIN_TRADE_SOURCE_FILES = ${JSON.stringify(sourceFiles, null, 2)};\n`
    + `const modules = new Map(${JSON.stringify(modules, null, 2)}.map(value => [value.entry.id, value]));\n`
    + 'export function findBuiltinTradeModule(id) {\n  const value = modules.get(id);\n  return value ? structuredClone(value) : null;\n}\n';
}
