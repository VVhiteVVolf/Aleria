import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { dirname, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEVELOPMENT_TRAITS } from '../modules/character-development/development-traits.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const output = resolve(root, 'AleriaAlmanach/modules/character-development/development-trait-revision-source.js');
const flag = process.argv.indexOf('--baseline');
const sourceFlag = process.argv.indexOf('--source-root');
const historicalRoot = sourceFlag >= 0 ? resolve(process.argv[sourceFlag + 1]) : null;
const baseline = flag >= 0 ? process.argv[flag + 1] : execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
if (!/^[a-f0-9]{40}$/.test(baseline || '')) throw Error('Pass a full immutable baseline commit.');
const urls = new Map();
function historicalModule(path) {
  if (urls.has(path)) return urls.get(path);
  if (!path.startsWith('AleriaAlmanach/modules/')) throw Error(`Unexpected historical dependency: ${path}`);
  const original = historicalRoot ? readFileSync(resolve(historicalRoot, path), 'utf8')
    : execFileSync('git', ['show', `${baseline}:${path}`], { cwd: root, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 });
  const code = original.replace(/(\bfrom\s*|\bimport\s*)['"]([^'"]+)['"]/g, (match, prefix, specifier) => {
    if (!specifier.startsWith('.')) throw Error(`Unexpected external dependency: ${specifier}`);
    return `${prefix}'${historicalModule(posix.normalize(posix.join(posix.dirname(path), specifier.split('?')[0])))}'`;
  });
  const url = `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`;
  urls.set(path, url);
  return url;
}
const old = await import(historicalModule('AleriaAlmanach/modules/character-development/development-traits.js'));
const current = new Map(DEVELOPMENT_TRAITS.map(entry => [entry.id, entry]));
const previous = old.DEVELOPMENT_TRAITS.filter(entry => current.has(entry.id) && JSON.stringify(entry) !== JSON.stringify(current.get(entry.id)));
const content = `// Immutable pre-balance catalog copies; used only for exact, reversible revisions.\n// Generated by tools/build-trait-balance-revision.mjs --baseline ${baseline}\nexport const TRAIT_BALANCE_BASELINE = '${baseline}';\nexport const PREVIOUS_DEVELOPMENT_TRAITS = ${JSON.stringify(previous, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw Error('Trait revision source is out of date.');
} else await writeFile(output, content);
console.log(JSON.stringify({ baseline, revisedCatalogEntries: previous.length }));
