import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile, access } from 'node:fs/promises';
import { planCaralynBiography } from '../modules/gwynthor-seven/caralyn-biography-import.mjs';
import { CARALYN_CHARACTER_ID } from '../modules/gwynthor-seven/caralyn-companion.js';
const source = JSON.parse(await readFile(new URL('../modules/gwynthor-seven/source/caralyn-biography-20261102.json', import.meta.url), 'utf8'));
const snapshot = JSON.parse(await readFile(new URL('../../diagnostics/combat-sheets-20261102/online-before.json', import.meta.url), 'utf8'));
const character = snapshot.collections.characters.records.find(record => record.id === CARALYN_CHARACTER_ID);
const now = '2026-11-03T00:00:00.000Z';
test('Caralyn imports only the authored biography and one linked horse, preserving money, gear and combat resources', async () => {
  const original = structuredClone(character), plan = planCaralynBiography(character, source, now);
  assert.deepEqual(Object.keys(plan.patch).sort(), ['biography', 'inventory', 'updatedAt']);
  assert.equal(plan.patch.biography.biography.biographyText, source.biography.biography.biographyText);
  assert.deepEqual(plan.patch.biography.biography.extraSections, source.biography.biography.extraSections);
  assert.equal(plan.patch.biography.biography.abilities.length, 10);
  for (const ability of plan.patch.biography.biography.abilities) await access(new URL('../../' + decodeURI(ability.icon).slice(1), import.meta.url));
  assert.equal(plan.creatures.length, 1);
  const horse = plan.creatures[0], card = plan.patch.inventory.companions.find(card => card.creatureId === horse.id);
  const item = plan.patch.inventory.items.find(item => item.creatureId === horse.id);
  assert.equal(horse.name, 'Eure Hufigkeit'); assert.equal(horse.itemOrigin.ownerCharacterId, character.id);
  assert.equal(horse.bestiaryReference.id, 'tiere/pferde/rhyfel'); assert.match(horse.species, /vermutlich/);
  assert.equal(card.inventoryItemId, item.id); assert.equal(item.instanceId, horse.itemOrigin.instanceId);
  assert(!JSON.stringify(plan.creatures).includes('Blubbrigkeit'));
  assert(!JSON.stringify(plan.patch.inventory).includes('Blubbrigkeit'));
  for (const item of character.inventory.items) assert.deepEqual(plan.patch.inventory.items.find(next => next.id === item.id), item);
  for (const key of Object.keys(character.inventory).filter(key => !['items', 'companions', 'revision'].includes(key))) assert.deepEqual(plan.patch.inventory[key], character.inventory[key]);
  const current = { ...character, ...plan.patch };
  assert.deepEqual(planCaralynBiography(current, source, now).patch.inventory, plan.patch.inventory);
  assert.deepEqual(character, original);
});
