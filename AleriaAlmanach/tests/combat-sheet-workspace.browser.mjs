 assert.equal(await page.locator('[data-sheet-search="traits"]').inputValue(),'eigensinn');
 await page.setViewportSize({width:390,height:844});
 await preview.capture('gawain-traits-phone');
 assert.ok(await page.locator('#cp-combat-sheet-root').evaluate(root=>root.scrollWidth<=root.clientWidth+2),'Mobile sheet must fit its viewport.');
 await page.locator('[data-sheet-page="overview"]').click();
 const strength=page.locator('[data-combat-collection="attributes"][data-combat-item-id="strength"][data-combat-property="score"]');
 await strength.fill('17');await strength.blur();
 await page.locator('[data-sheet-page="arsenal"]').click();await page.locator('[data-sheet-page="overview"]').click();
 assert.equal(await strength.inputValue(),'17');
 await page.setViewportSize({width:1440,height:1000});
 const asgeir=structuredClone(characters.find(character=>character.name==='Asgeir Wolfshorn'));
 const customWeapon=asgeir.combatProfile.weapons.find(weapon=>weapon.inventoryItemId);
 customWeapon.damageFormula='1d4+9';
 await page.evaluate(character=>AleriaCharacterCombatProfile.init(character),asgeir);
 assert.equal((await page.evaluate(()=>AleriaCharacterCombatProfile.collect())).weapons.find(weapon=>weapon.id===customWeapon.id).damageFormula,'1d4+9');
 const rhiannon=characters.find(character=>character.name==='Rhiannon Draig');
 await page.evaluate(character=>AleriaCharacterCombatProfile.init(character),rhiannon);
 await page.locator('[data-sheet-page="magic"]').click();
 assert.equal(await page.locator('#cs-page-magic [data-spell-id]').count(),23);
 await preview.capture('rhiannon-magic-desktop');
