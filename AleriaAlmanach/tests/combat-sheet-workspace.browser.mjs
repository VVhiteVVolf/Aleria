 await preview.capture('gawain-overview-desktop');
 const inputCount=await page.locator('#cp-combat-sheet-root input').count();
 for(const id of ['arsenal','traits','magic','resources','rules','overview']){
  await page.locator(`[data-sheet-page="${id}"]`).click();
  assert.equal(await page.locator('.cs-page:visible').count(),1);
  assert.equal(await page.locator('#cp-combat-sheet-root input').count(),inputCount);
 }
 assert.deepEqual(await page.evaluate(()=>AleriaCharacterCombatProfile.collect()),baseline,'Navigation must preserve the complete draft.');
 await page.locator('[data-sheet-page="arsenal"]').click();
 await preview.capture('gawain-arsenal-desktop');
 await page.locator('[data-sheet-page="traits"]').click();
