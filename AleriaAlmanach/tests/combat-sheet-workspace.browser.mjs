 assert.deepEqual(preview.errors,[]);
 await writeFile(resolve(preview.output,'report.json'),JSON.stringify({passed:true,characterDraftPreserved:true,creatureNodesRetained:true,mobileOverflow:false,errors:preview.errors},null,2)+'\n');
 console.log(JSON.stringify({passed:true,output:preview.output}));
