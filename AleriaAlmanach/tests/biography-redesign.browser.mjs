import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { openVenueBrowserPreview } from './support/venue-browser-preview.mjs';
const preview = await openVenueBrowserPreview('biography-redesign-20261102');
const { page } = preview;
try {
  await page.setViewportSize({ width: 1680, height: 1050 });
  const { GAIS_WYRM_BIOGRAPHY } = await import('../../Stammbäume/assets/js/data/person-biographies/gais-wyrm.js');
  const biography = await page.evaluate(bio => AleriaBiographyCatalog.resolve(bio,{worldPersonId:'person--haus-wyrm--gais-wyrm'}), GAIS_WYRM_BIOGRAPHY);
  const entry = { id: 'bio-qa', multipage: true, title: 'Gais Wyrm', image: '../Stammbäume/assets/images/portraits/haus-wyrm/gais-wyrm.jpg', pages: [{ biographyPage: true, ...biography }] };
  await preview.openPage(entry, 0);
  assert.ok(await page.locator('#modal-overlay .biography-section').count() > 5);
  await preview.capture('module-desktop');
  await page.evaluate(bio => {
    closeModal(); openCharProfile(null); switchCharTab('biography');
    document.getElementById('cp-name').value='Gais Wyrm';
    document.getElementById('cp-portrait-img').src='../Stammbäume/assets/images/portraits/haus-wyrm/gais-wyrm.jpg';
    document.getElementById('cp-portrait-img').style.display='';
    initCharacterBiographyTab({ biography: bio });
  }, biography);
  await page.locator('[data-cp-biography-action="edit"]').click();
  const groups = page.locator('#cp-biography-editor .biography-editor-group');
  assert.equal(await groups.count(), 11);
  assert.equal(await groups.locator(':scope[open]').count(), 0);
  await preview.capture('character-editor-desktop');
  await groups.filter({hasText:'Ritterväter & Rittermütter'}).locator('summary').click();
  await page.locator('#cp-biography-editor [data-module-editor-action="add-biography-mentor-row"]').click();
  await page.locator('#cp-biography-editor [data-mentor-field="name"]').last().fill('Testausbilder');
  const value=await page.evaluate(()=>collectCharacterBiographyData());
  assert.equal(value.biography.knightMentors.at(-1).name,'Testausbilder');
  await page.locator('#cp-biography-editor [data-module-editor-action="remove-biography-mentor-row"]').last().click();
  await groups.filter({hasText:'Biografie & Hintergrund'}).locator('summary').click();
  const narrative=page.locator('#cp-biography-editor .module-rich-editor.me-biography-text');
  await narrative.fill('Erster Absatz');
  await narrative.press('End'); await narrative.press('Enter'); await narrative.type('Zweiter Absatz');
  assert.match((await page.evaluate(()=>collectCharacterBiographyData())).biography.biographyText,/Erster Absatz.*(?:<div>|<p>|<br>).*Zweiter Absatz/s);
  await narrative.fill('Ein Zwischentitel'); await narrative.press('Control+A');
  const richScope=narrative.locator('..');
  await richScope.locator('[data-richtext-command="subheading"]').click();
  await narrative.press('End');
  await richScope.locator('[data-richtext-command="divider"]').click();
  const formatted=await page.evaluate(()=>collectCharacterBiographyData());
  assert.match(formatted.biography.biographyText,/<h4>.*?Ein Zwischentitel.*?<\/h4>/);
  assert.match(formatted.biography.biographyText,/<hr>/);
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-cp-biography-action="toggle-maximize"]').click();
  assert.equal(await page.locator('.cp-biography-edit-preview').isVisible(),false);
  assert.equal(await page.locator('.cp-biography-edit-divider').isVisible(),false);
  await page.locator('[data-cp-biography-action="toggle-preview"]').click();
  assert.equal(await page.locator('.cp-biography-edit-preview').isVisible(),true);
  assert.equal(await page.locator('.cp-biography-edit-form').isVisible(),false);
  await page.locator('[data-cp-biography-action="toggle-preview"]').click();
  assert.equal(await page.locator('.cp-biography-edit-form').isVisible(),true);
  await preview.capture('character-editor-phone');
  const charBounds=await page.locator('.cp-biography-edit-form').evaluate(el=>({width:el.clientWidth,scroll:el.scrollWidth}));
  assert.ok(charBounds.scroll<=charBounds.width+2);
  await page.evaluate(()=>closeCharProfile());
  // Isolate the feature dialog from the tree app's existing dialog controller;
  // creating two controllers on the same live dialog would double-handle clicks.
  const treeHtml=await readFile(new URL('../../Stammbäume/Stammbaum.html',import.meta.url),'utf8');
  const treeHead=treeHtml.match(/<head>([\s\S]*?)<\/head>/)[1];
  const treeUrl=preview.origin+'/Stammb%C3%A4ume/biography-qa.html';
  await page.route(treeUrl,route=>route.fulfill({contentType:'text/html',body:`<!doctype html><html lang="de"><head>${treeHead}</head><body><dialog class="dialog person-biography-dialog" id="person-biography-dialog"></dialog></body></html>`}));
  await page.goto(treeUrl);
  await page.evaluate(async bio=>{
    const {createPersonBiographyDialog}=await import('./assets/js/modules/person-biography/person-biography-dialog.js');
    globalThis.qaBiographyDialog=createPersonBiographyDialog({onSave:(_id,bio)=>{globalThis.qaSavedBiography=bio;}});
    qaBiographyDialog.open({id:'gais-wyrm',name:'Gais Wyrm',portrait:'assets/images/portraits/haus-wyrm/gais-wyrm.jpg',extensions:{biographyModule:bio}},{editable:true});
  },biography);
  assert.equal(await page.locator('[data-biography-preview]').isVisible(),false);
  await page.locator('[data-biography-action="toggle-preview"]').click();
  assert.equal(await page.locator('[data-biography-preview]').isVisible(),true);
  assert.equal(await page.locator('.person-biography-dialog__editor-pane').isVisible(),false);
  await preview.capture('tree-preview-phone');
  await page.locator('[data-biography-action="toggle-preview"]').click();
  const treeTextGroup=page.locator('.person-biography-editor .biography-editor-group').filter({hasText:'Biografie & Hintergrund'});
  await treeTextGroup.locator('summary').click();
  const treeNarrative=page.locator('[data-biography-rich-field="biographyText"]');
  await treeNarrative.fill('Stammbaum-Zwischentitel'); await treeNarrative.press('Control+A');
  await treeNarrative.locator('..').locator('[data-biography-command="subheading"]').click();
  await treeNarrative.press('End'); await treeNarrative.locator('..').locator('[data-biography-command="divider"]').click();
  const treeBounds=await page.locator('.person-biography-dialog__editor-pane').evaluate(el=>({width:el.clientWidth,scroll:el.scrollWidth}));
  assert.ok(treeBounds.scroll<=treeBounds.width+2);
  await preview.capture('tree-editor-phone');
  await page.setViewportSize({width:1680,height:1050});
  await preview.capture('tree-editor-desktop');
  const widths=await page.locator('.biography-editor-group__body').evaluateAll(nodes=>nodes.filter(n=>n.closest('details').open).map(n=>({width:n.clientWidth,scroll:n.scrollWidth})));
  assert.ok(widths.every(w=>w.scroll<=w.width+2));
  await page.locator('.biography-editor-menu > summary').click();
  assert.equal(await page.locator('[data-biography-action="import-module"]').isVisible(),true);
  assert.equal(await page.locator('[data-biography-action="export-module"]').isVisible(),true);
  await page.locator('.biography-editor-menu > summary').click();
  await page.getByRole('button',{name:'Biographie speichern',exact:true}).click();
  const saved=await page.evaluate(()=>qaSavedBiography);
  assert.match(saved.biography.biographyText,/<h4>.*?Stammbaum-Zwischentitel.*?<\/h4>/);
  assert.match(saved.biography.biographyText,/<hr>/);
  assert.deepEqual(saved.biography.knightMentors,biography.biography.knightMentors);
  await page.goto(preview.origin+'/AleriaAlmanach/AleriaAlmanach.html');
  await page.waitForFunction(()=>typeof openModal==='function'&&['ready','slow'].includes(document.querySelector('[data-loading-screen]')?.dataset.state));
  const enter=page.locator('[data-loading-action="enter"]');
  await (await enter.isEnabled()?enter:page.locator('[data-loading-action="continue"]')).click();
  await page.evaluate(entry=>{
    _inlineModuleEdit={active:true,mode:'edit',sourceKind:'new',entryId:entry.id,section:getPreferredEditorSection(),draft:sanitizeModuleEntry(entry)};
    openModal(entry,{pageIndex:0});
  },entry);
  const inlineGroups=page.locator('.inline-module-edit-pane [data-biography-editor-group]');
  assert.equal(await inlineGroups.count(),11);
  await inlineGroups.filter({hasText:'Ritterväter & Rittermütter'}).locator('summary').click();
  await page.locator('[data-inline-action="add-biography-mentor"]').click();
  const inlineName=page.locator('[data-inline-action="update-biography-mentor"][data-biography-mentor-field="name"]').last();
  await inlineName.fill('Inline-Testausbilder');
  assert.equal(await page.evaluate(()=>getInlineDraftPage().biography.knightMentors.at(-1).name),'Inline-Testausbilder');
  await page.locator('[data-inline-action="remove-biography-mentor"]').last().click();
  assert.equal(await page.evaluate(()=>getInlineDraftPage().biography.knightMentors.length),2);
  await preview.capture('inline-editor-desktop');
  assert.deepEqual(preview.errors,[]);
  await writeFile(resolve(preview.output,'report.json'),JSON.stringify({passed:true,widths,charBounds,treeBounds,paragraphsAndHeadingsRetained:true,mobilePreviewToggle:true,inlineMentors:true,externalWritesBlocked:true,errors:preview.errors},null,2)+'\n');
  console.log(JSON.stringify({passed:true,output:preview.output,errors:preview.errors}));
} catch (error) {
  await preview.capture('failure');
  await writeFile(resolve(preview.output,'failure.json'),JSON.stringify({message:error.message,errors:preview.errors},null,2)+'\n');
  throw error;
} finally { await preview.close(); }
