import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { openVenueBrowserPreview } from './support/venue-browser-preview.mjs';
import { DEVELOPMENT_TRAITS } from '../modules/character-development/development-traits.js';

const {characters} = JSON.parse(await readFile(new URL('../modules/gwynthor-seven/source/character-plan.json',import.meta.url),'utf8'));
const preview = await openVenueBrowserPreview('character-setup-redesign-20261102');
const {page} = preview;
try {
  const rianna = characters.find(c=>c.name==='Rianna Wyrm');
  await page.evaluate(c=>{openCharProfile(null);switchCharTab('combat');AleriaCharacterCombatProfile.init(c);},rianna);
  const before = await page.evaluate(()=>AleriaCharacterCombatProfile.collect());
  await page.locator('[data-combat-action="open-character-setup"]').click();
  const dialog = page.locator('[data-character-creation-root]');
  assert.equal(await dialog.locator('[data-creation-action="go-step"]').count(),7);
  assert.equal(await dialog.locator('.development-window').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(25, 27, 24)');
  await dialog.locator('[data-creation-field="classId"]').selectOption('helwyr');
  await dialog.locator('[data-creation-action="go-step"][data-step="2"]').click();
  assert.equal(await dialog.locator('[data-creation-skill-check="perception"]').isChecked(),false);
  await dialog.locator('[data-creation-skill-check="perception"]').check();
  await dialog.locator('[data-creation-skill="perception"]').selectOption('expertise');
  await dialog.locator('[data-creation-skill-check="athletics"]').check();
  await preview.decodeImages('.cp-creation-skill img');
  await page.setViewportSize({width:1440,height:1000});
  await preview.capture('skills-desktop');
  await dialog.locator('[data-creation-action="go-step"][data-step="3"]').click();
  await dialog.locator('[data-creation-class="teulu"]').check();
  await dialog.locator('[data-creation-field="classId"]').selectOption('teulu');
  assert.equal(await dialog.locator('[data-creation-class="helwyr"]').isChecked(),true);
  await dialog.locator('[data-creation-field="classId"]').selectOption('helwyr');
  assert.equal(await dialog.locator('[data-creation-class="teulu"]').isChecked(),true);
  await dialog.locator('[data-creation-field="includeCustomClass"]').check();
  await dialog.locator('[data-creation-custom="name"]').fill('Hafenwächterin');
  await dialog.locator('[data-creation-training="hitDieOverride"]').selectOption('8');
  await dialog.locator('[data-creation-training="magicMode"]').selectOption('focus');
  await dialog.locator('[data-creation-save="strength"]').uncheck();
  await dialog.locator('[data-creation-save="constitution"]').uncheck();
  await dialog.locator('[data-creation-save="dexterity"]').check();
  await dialog.locator('.creation-typical-weapons summary').click();
  await preview.decodeImages('.creation-class-picker img, .creation-save-options img, .creation-typical-weapons img');
  await dialog.locator('.cp-setup-body').evaluate(element=>element.scrollTop=0);
  await preview.capture('classes-desktop');
  assert.equal(await dialog.getByText('Startausrüstung',{exact:true}).count(),0);
  await dialog.locator('[data-creation-action="go-step"][data-step="4"]').click();
  await dialog.locator('[data-level-up-path="targetLevel"]').fill('5');
  assert.equal(await dialog.locator('[data-development-trait]').count(),DEVELOPMENT_TRAITS.length);
  await dialog.locator('[data-development-purchase]').first().check();
  await dialog.getByText('Balance und Preise anpassen',{exact:true}).click();
  await dialog.locator('[data-level-up-path="development.startingPoints"]').fill('0');
  await dialog.locator('[data-level-up-path="development.pointsPerLevel"]').fill('0');
  await dialog.locator('[data-development-trait="development-trait-heilerhaende"]').check();
  await dialog.locator('[data-development-trait="development-trait-gelenkig"]').check();
  assert.match(await dialog.locator('[data-development-role="balance"]').innerText(),/-\d+ Balancepunkte/);
  await dialog.locator('[data-level-up-path="traitGroup"]').selectOption('selected');
  assert.equal(await dialog.locator('[data-development-trait]').count(),2);
  await dialog.locator('[data-development-action="reset-choices"]').click();
  assert.equal(await dialog.locator('[data-development-trait]:checked').count(),0);
  await dialog.locator('[data-level-up-path="traitGroup"]').selectOption('all');
  await dialog.locator('[data-development-trait="development-trait-heilerhaende"]').check();
  await dialog.locator('[data-development-trait="development-trait-gelenkig"]').check();
  await dialog.locator('[data-development-purchase]').first().check();
  await dialog.locator('[data-level-up-path="traitGroup"]').selectOption('bloodline');
  assert.equal(await dialog.locator('[data-development-trait]').count(),10);
  await dialog.locator('[data-development-trait="development-trait-bluttraeger-nymphenspross"]').check();
  await preview.decodeImages('.development-trait img');await preview.capture('bloodlines-desktop');
  await dialog.locator('[data-level-up-path="traitGroup"]').selectOption('symbiosis');
  assert.equal(await dialog.locator('[data-development-trait]').count(),4);
  assert.equal(await dialog.locator('.development-clan-emblem').count(),4);
  assert.equal(await dialog.locator('.development-clan-emblem').first().evaluate(el=>el.getBoundingClientRect().width),22);
  assert.match(await dialog.locator('[data-development-role="traits"]').innerText(),/Silvanische Symbiose der Dál Haig \(Bär\)/);
  await dialog.locator('[data-development-trait="development-trait-symbiose-haig-baer"]').check();
  await preview.decodeImages('.development-trait img');await preview.capture('symbiose-desktop');
  await dialog.locator('[data-level-up-path="traitGroup"]').selectOption('all');
  await preview.decodeImages('.development-trait img');
  const views = [];
  for (const [name,size] of [['desktop',{width:1440,height:1000}],['phone',{width:390,height:844}]]) {
    await page.setViewportSize(size);
    const bounds = await dialog.locator('.cp-setup-dialog').evaluate(el=>({width:el.clientWidth,scrollWidth:el.scrollWidth}));
    assert.ok(bounds.scrollWidth <= bounds.width+2,name);
    await preview.capture(name);
    views.push({name,...bounds});
  }
  await dialog.locator('[data-level-up-path="traitGroup"]').selectOption('symbiosis');
  await dialog.locator('.development-trait').first().scrollIntoViewIfNeeded();
  await preview.decodeImages('.development-trait img');await preview.capture('symbiose-phone');
  await dialog.locator('[data-creation-action="go-step"][data-step="5"]').click();
  await dialog.locator('summary').filter({hasText:'Vorräte individuell anpassen'}).click();
  await dialog.locator('[data-level-up-resource="mana-focus"][data-level-up-resource-property="maximum"]').fill('7');
  await dialog.locator('[data-creation-action="go-step"][data-step="6"]').click();
  assert.equal(await dialog.locator('[data-creation-action="apply"]').isEnabled(),true);
  await preview.capture('review-phone');
  await dialog.locator('[data-creation-action="apply"]').click();
  const after = await page.evaluate(()=>AleriaCharacterCombatProfile.collect());
  assert.equal(after.progression.level,5);
  assert.equal(after.templateSelections.classId,'helwyr');
  assert.deepEqual(after.templateSelections.classIds,['helwyr','teulu','custom']);
  assert.equal(after.templateSelections.customClass.name,'Hafenwächterin');
  assert.equal(after.skills.find(skill=>skill.name==='Wahrnehmung').proficiency,'expertise');
  assert.equal(after.skills.find(skill=>skill.name==='Athletik').proficiency,'trained');
  assert.equal(after.skills.find(skill=>skill.name==='Überreden').proficiency,'none');
  assert.equal(after.skills.find(skill=>skill.name==='Naturkunde').proficiency,'none');
  assert.equal(after.hitPoints.hitDie,8);assert.equal(after.magic.focusEnabled,true);
  assert.equal(after.techniques.length,1);
  assert.equal(after.quirks.filter(q=>q.id.startsWith('development-trait-')).length,4);
  assert.ok(after.quirks.some(q=>q.id==='development-trait-bluttraeger-nymphenspross'&&q.tags.includes('Angeboren')));
  assert.ok(after.quirks.some(q=>q.id==='development-trait-symbiose-haig-baer'&&q.tags.includes('Angeboren')));
  assert.equal(after.resources.find(r=>r.id==='mana-focus').maximum,7);
  assert.deepEqual(after.weapons.map(w=>[w.id,w.name]),before.weapons.map(w=>[w.id,w.name]));
  assert.deepEqual(after.armorItems.map(a=>[a.id,a.name]),before.armorItems.map(a=>[a.id,a.name]));
  assert.ok(!after.weapons.some(w=>w.id.startsWith('starter-')));
  assert.deepEqual(preview.errors,[]);
  await writeFile(resolve(preview.output,'report.json'),JSON.stringify({passed:true,views,level:5,attacks:1,traits:4,bloodlineFilter:10,symbiosisFilter:4,clanEmblems:4,negativeBalanceAllowed:true,standardEquipmentGranted:0,existingEquipmentPreserved:true,externalWritesBlocked:true,errors:preview.errors},null,2)+'\n');
  console.log(JSON.stringify({passed:true,output:preview.output}));
} catch(error) {
  await writeFile(resolve(preview.output,'failure.json'),JSON.stringify({error:error.message,errors:preview.errors},null,2)+'\n');
  await preview.capture('failure');
  throw error;
} finally { await preview.close(); }
