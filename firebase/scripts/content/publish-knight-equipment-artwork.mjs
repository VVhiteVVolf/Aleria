// Explicitly bounded to the four requested inventories; never deploys the site.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createContentPublicationClient } from './content-publication-client.mjs';
import { buildGwynthorSevenItems, GWYNTHOR_SEVEN_LOADOUTS } from '../../../AleriaAlmanach/modules/gwynthor-seven/equipment.mjs';
import { KNIGHT_EQUIPMENT_TARGETS } from '../../../AleriaAlmanach/modules/gwynthor-seven/knight-equipment-plan.mjs';
import { buildKnightStartingItems } from '../../../AleriaAlmanach/modules/gwynthor-seven/starting-possessions.mjs';
import { GWYNTHOR_EQUIPMENT_ARTWORK } from '../../../AleriaAlmanach/modules/gwynthor-seven/equipment-artwork.mjs';

const apply = process.argv.includes('--apply');
const root = fileURLToPath(new URL('../../../', import.meta.url));
const output = new URL('../../../AleriaAlmanach/modules/gwynthor-seven/equipment-artwork.mjs', import.meta.url);
const directory = new URL('../../../diagnostics/knight-equipment-20261102/', import.meta.url);
const templates = buildGwynthorSevenItems({ publishedArtwork: false });
const sources = new Map();
for (const target of KNIGHT_EQUIPMENT_TARGETS) {
  for (const [key] of GWYNTHOR_SEVEN_LOADOUTS[target.key]) {
    const item = templates.find(item => item.id === `gwynthor-seven:${key}`);
    assert(item?.image, `Bild fehlt: ${key}`);
    if (!sources.has(item.image)) sources.set(item.image, { familyId: target.familyId, items: [] });
    sources.get(item.image).items.push(item.id);
  }
}
if (process.argv.includes('--include-starting')) {
  for (const item of buildKnightStartingItems({ publishedArtwork: false })) sources.set(item.image, { familyId: 'haus-draig', items: [item.id] });
}
const client = apply ? await createContentPublicationClient() : null;
const artwork = { ...GWYNTHOR_EQUIPMENT_ARTWORK };
for (const [source, owner] of sources) {
  let bytes;
  if (source.startsWith('/AleriaAlmanach/')) {
    const path = resolve(root, source.slice(1));
    assert(path.startsWith(resolve(root, 'AleriaAlmanach') + sep), 'Bildpfad außerhalb des Features');
    bytes = await readFile(path);
  } else {
    assert.equal(source, 'https://i.imgur.com/bthNwPb.png', 'Nicht freigegebene externe Bildquelle');
    const response = await fetch(source, { signal: AbortSignal.timeout(30000) });
    assert(response.ok, `Originalbild: HTTP ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
  }
  const png = bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
  const jpeg = bytes[0] === 255 && bytes[1] === 216;
  assert(png || jpeg, `Kein PNG/JPEG: ${source}`);
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  const receipt = client ? await client.publishFamilyArtwork({ familyId: owner.familyId,
    assetId: `knight-equipment-${sha256.slice(0, 16)}`, bytes,
    contentType: png ? 'image/png' : 'image/jpeg',
    metadata: { sourceFeature: 'knight-equipment-20261102', sourcePath: source } }) : {};
  artwork[source] = { ...receipt, sha256, size: bytes.length, sourceItems: [...new Set(owner.items)] };
}
await mkdir(directory, { recursive: true });
if (apply) await writeFile(output,
  '// Published original equipment artwork. Generated by firebase/scripts/content/publish-knight-equipment-artwork.mjs.\n'
  + `export const GWYNTHOR_EQUIPMENT_ARTWORK = ${JSON.stringify(artwork, null, 2)};\n`);
const report = { capturedAt: new Date().toISOString(), applied: apply, imageCount: sources.size, artwork };
await writeFile(new URL(apply ? 'artwork-published.json' : 'artwork-plan.json', directory), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ applied: apply, images: sources.size, totalBytes: Object.values(artwork).reduce((n, item) => n + item.size, 0) }));
