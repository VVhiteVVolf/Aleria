import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { writeClassPageOutput } from './class-page-output.mjs';

// Class-owned snapshot: later edits or level-ups of Freya must not silently
// rewrite the shared class, expose personal traits or break its build.
const root = new URL('../../', import.meta.url);
const snapshot = JSON.parse(await readFile(new URL('Klassenordner/Aldrimar/skalde/referenz-freya.json', root), 'utf8'));
assert.equal(snapshot.schemaVersion, 1);
assert.equal(snapshot.referenceLevel, 5);
assert.match(snapshot.sourceProfileHash, /^[a-f0-9]{64}$/);
assert.equal(snapshot.repertoire.length, 9);
assert.equal(new Set(snapshot.repertoire.map(entry => entry.sourceId)).size, 9);
assert(snapshot.repertoire.every(entry => entry.minimumLevel >= 1 && entry.minimumLevel <= 5 && entry.active === false));
assert(snapshot.repertoire.every(entry => entry.costs.every(cost => cost.resourceId && cost.amount > 0)));
const { schemaVersion, capturedFor, ...reference } = snapshot;
await writeClassPageOutput(root, 'AleriaAlmanach/modules/classes/aldrimar/skald-freya-reference.js',
  `// Generated by Klassenordner/scripts/build-skald-reference.mjs. Read-only reference, not character grants.\nexport const SKALD_FREYA_REFERENCE = ${JSON.stringify(reference, null, 2)};\n`, process.argv.includes('--check'));
console.log('Skaldenreferenz: acht Lieder und Arkaner Schrei aus dem festgehaltenen Freya-Stand geprüft.');
