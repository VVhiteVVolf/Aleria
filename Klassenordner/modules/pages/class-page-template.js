import { renderContents, renderIllustration, renderFacts, renderSection, renderPending } from './class-page-sections.js';
import { escapeClassHtml as escape } from './class-page-content.js';
import { getArmorRoutine } from '../../../AleriaAlmanach/modules/classes/armor-routine.js';

const ASSET_VERSION = '20260905-universal-v1';
const FALLBACK_ICON = '../../../IconOrdner/ReiterIcons/Klassen.png';
function renderClassList(documents, currentId) {
  return `<nav class="class-volume-nav" aria-label="Universalklassen"><p class="eyebrow">Die fünfzehn Wege</p><ul>${documents.map(document =>
    `<li><a href="../${document.id}/index.html"${document.id === currentId ? ' aria-current="page"' : ''}>${escape(document.name)}</a></li>`).join('')}</ul></nav>`;
}
export function renderUniversalClassPage(document, documents) {
  const index = documents.findIndex(entry => entry.id === document.id);
  const previous = documents[(index + documents.length - 1) % documents.length];
  const next = documents[(index + 1) % documents.length];
  const written = document.sections.filter(section => section.status === 'written');
  const armorRoutine = getArmorRoutine({ templateSelections: { classId: document.id } });
  if (armorRoutine) written.push({ id: 'ruestungsroutine', title: `${armorRoutine.name} · Stufe 12`,
    html: `<p>${escape(armorRoutine.description)}</p>` });
  const pending = document.sections.filter(section => section.status === 'pending');
  return `<!doctype html>
<!-- Generated by Klassenordner/scripts/build-universal-classes.mjs. Edit this class's klasse.json or the shared template. -->
<html lang="de">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escape(document.name)} in Aleria: ${escape(document.subtitle)}. Herkunft, Wesen und überlieferte Fähigkeiten dieser Universalklasse.">
  <title>${escape(document.name)} · Universalklassen · Aleria</title>
  <link rel="stylesheet" href="../../assets/css/klassen.css?v=${ASSET_VERSION}">
  <link rel="stylesheet" href="../../modules/pages/class-page.css?v=${ASSET_VERSION}">
  <script type="module" src="../../modules/pages/class-page.js?v=${ASSET_VERSION}"></script>
</head>
<body class="classes-page class-document-page" data-class-document="${document.id}" data-class-theme="${document.theme}" id="top">
  <a class="skip-link" href="#einfuehrung">Zum Klasseninhalt</a>
  <header class="site-header"><a href="../../Klassenseite.html#basis">← Zum Klassenregister</a><span class="site-brand">Aleria <span aria-hidden="true">/</span> Codex der Klassen</span><a class="class-almanach-link" href="../../../AleriaAlmanach/AleriaAlmanach.html">Zum Almanach</a></header>
  <div class="class-book">
    <aside class="class-book-navigation">
      <a class="class-book-mark" href="../../Klassenseite.html#basis"><img src="${FALLBACK_ICON}" alt="" width="48" height="48"><span>Codex<br>der Klassen</span></a>
      ${renderContents(written, pending.length > 0)}
      ${renderClassList(documents, document.id)}
    </aside>
    <main class="class-book-page">
      <header class="class-cover">
        <div class="class-cover-top"><p class="eyebrow">Universalklassen · Aleria</p><span class="class-volume-number">${String(index + 1).padStart(2, '0')} / ${documents.length}</span></div>
        <div class="class-cover-title"><div class="class-emblem"><img src="${escape(document.icon || FALLBACK_ICON)}" alt="" width="100" height="100" data-role="class-icon" data-fallback-src="${FALLBACK_ICON}"></div><div><p class="class-cover-kind">${escape(document.name)} · Universalklasse</p><h1>${escape(document.title)}</h1><p class="class-cover-subtitle">${escape(document.subtitle)}</p></div></div>
        <div class="class-cover-rule" aria-hidden="true"><span>◆</span></div>
      </header>
      <details class="class-mobile-nav"><summary>Inhalt &amp; Universalklassen</summary>${renderContents(written, pending.length > 0)}${renderClassList(documents, document.id)}</details>
      <div class="class-reading-layout">
        <div class="class-chapters">${written.map(renderSection).join('\n')}${renderPending(pending)}</div>
        <aside class="class-reference" aria-label="Illustration und Klassenprofil">${renderIllustration(document)}${renderFacts(document)}</aside>
      </div>
      <nav class="class-next-pages" aria-label="Weitere Klassen"><a href="../${previous.id}/index.html"><span>← Vorherige Klasse</span><strong>${escape(previous.name)}</strong></a><a href="../${next.id}/index.html"><span>Nächste Klasse →</span><strong>${escape(next.name)}</strong></a></nav>
      <footer class="catalog-footer"><span>Aleria · Universalklassen</span><div><button type="button" class="class-print-button" data-action="print-class" hidden>Drucken</button><a href="#top">Nach oben ↑</a></div></footer>
    </main>
  </div>
</body>
</html>
`;
}

