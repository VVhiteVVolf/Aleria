import { escapeClassHtml as escape } from '../pages/class-page-content.js';
import { renderContents, renderIllustration, renderFacts, renderSection, renderPending } from '../pages/class-page-sections.js';
import { renderCultureClassTraining } from './culture-class-training-template.js?v=20260909-dragon-parent-v2';
import { getCultureOrderContentsEntry, renderCultureOrderOverview } from './culture-order-overview.js';

const VERSION = '20260911-venalys-v1';
const STRUCTURE_ONLY_VERSION = '20260911-structure-only-v1';
const FALLBACK = '../../../IconOrdner/ReiterIcons/Klassen.png';
const CULTURE_FOLDERS = Object.freeze({
  cenyr: 'Cenyr',
  vennyr: 'Vennyr',
  aldrimar: 'Aldrimar',
  alben: 'Alben',
  nordmaenner: 'Nordmaenner',
  morgorn: 'Morgorn',
  venalys: 'Venalys'
});

function culturePageLabels(culture) {
  const fallbackTraditions = ['Traditionen', `${culture.name}s`];
  const traditionsLines = culture.pageLabels?.traditionsLines || fallbackTraditions;
  return {
    brand: culture.pageLabels?.brand || `${culture.name}s Klassen`,
    collection: culture.pageLabels?.collection || `Die Wege ${culture.name}s`,
    traditions: traditionsLines.map(escape).join('<br>')
  };
}

function pageHref(document) {
  return `../../${CULTURE_FOLDERS[document.cultureId]}/${document.id}/index.html`;
}

function cultureNavigation(documents, currentId, culture) {
  const labels = culturePageLabels(culture);
  return `<nav class="class-volume-nav" aria-label="${escape(culture.name)}-Klassen"><p class="eyebrow">${escape(labels.collection)}</p><ul>${documents.map(document => `<li><a href="${pageHref(document)}"${document.id === currentId ? ' aria-current="page"' : ''}>${escape(document.name)}</a></li>`).join('')}</ul></nav>`;
}

function sharedCultureNote(document) {
  if (!['derwyn', 'milwr'].includes(document.id)) return '';
  const links = document.id === 'milwr'
    ? '<a href="../../Cenyr/milwr/index.html">Cenyr · Drachling</a><a href="../../Vennyr/milwr/index.html">Vennyr · Küstenwache</a>'
    : '<a href="../../Klassenseite.html#cenyr">Im Register Cenyrs</a><a href="../../Klassenseite.html#vennyr">Im Register Vennyrs</a>';
  return `<aside class="culture-shared-class"><strong>Gemeinsame Klasse · Cenyr &amp; Vennyr</strong><p>${document.id === 'milwr' ? 'Zwei kulturelle Ausbildungswege derselben Klasse. Eine Herkunft verleiht keine zusätzlichen Attackenslots.' : 'Ein gemeinsames Klassenprofil für die Geistlichen Nimues beider Kulturen. Jungdrache oder junge Welle bilden die wählbare Grundlage; Schwert, Dreizack, Stab und Morgenstern führen in die vier eigenen Wyrmformen.'}</p><div>${links}</div></aside>`;
}

export function renderCultureClassPage(document, documents, culture, plan) {
  const written = document.sections.filter(section => section.status === 'written');
  const pending = document.sections.filter(section => section.status === 'pending');
  const hasProgression = Boolean(plan);
  const orderContents = getCultureOrderContentsEntry(culture);
  const loreContents = [written[0], ...(orderContents ? [orderContents] : []), ...written.slice(1)];
  const contents = hasProgression
    ? [loreContents[0], { id: 'ausbildungsplan', title: 'Ausbildung · Stufe 1–20' }, ...loreContents.slice(1)]
    : loreContents;
  const index = documents.findIndex(entry => entry.id === document.id);
  const previous = documents[(index + documents.length - 1) % documents.length];
  const next = documents[(index + 1) % documents.length];
  const companion = document.companionArtwork;
  const structureOnly = plan?.progressionStatus === 'structure-only';
  const styleName = hasProgression
    ? structureOnly ? 'Ausbildungsrahmen' : document.id === 'derwyn' ? 'Wyrmtanz' : plan.styles[0]?.name || 'Skaldisches Repertoire'
    : '';
  const trainingLabel = structureOnly
    ? 'Struktur 1–20 · Inhalte offen'
    : hasProgression && plan.authoredThroughLevel === 5 ? 'Ausbildung 1–5 · 6–20 offen' : 'Ausbildung 1–20';
  const focus = hasProgression ? plan.focus : document.subtitle;
  const affiliation = hasProgression ? plan.affiliation : `${document.subtitle} · ${culture.name}`;
  const progressionAttribute = hasProgression ? ` data-culture-class="${escape(plan.id)}"` : '';
  const orderOverview = renderCultureOrderOverview(culture, { currentClassId: document.id, classHref: classId => pageHref({ cultureId: culture.id, id: classId }) });
  const cultureStyle = ['vennyr', 'aldrimar', 'alben', 'nordmaenner', 'morgorn', 'venalys'].includes(culture.id)
    ? `<link rel="stylesheet" href="../../modules/culture/${culture.id}-class-page.css?v=${VERSION}">`
    : '';
  const labels = culturePageLabels(culture);
  return `<!doctype html>
<!-- Generated by Klassenordner/scripts/build-culture-classes.mjs. Edit klasse.json, kultur.json or the shared templates. -->
<html lang="de"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escape(document.name)} · ${escape(culture.name)}: ${escape(focus)}.${hasProgression ? ` Kultur, Herkunft und ${escape(styleName)}-Ausbildung von Stufe 1 bis 20.` : ' Herkunft, Rolle, Fähigkeiten und kultureller Status.'}">
  <title>${escape(document.name)} · ${document.id === 'derwyn' ? 'Cenyr &amp; Vennyr' : escape(culture.name)} · Aleria</title>
  <link rel="stylesheet" href="../../assets/css/klassen.css?v=20260905-universal-v1">
  <link rel="stylesheet" href="../../modules/pages/class-page.css?v=20260905-universal-v1">
  <link rel="stylesheet" href="../../modules/culture/culture-class-page.css?v=${VERSION}">
  ${hasProgression && ['vennyr', 'aldrimar'].includes(culture.id) ? `<link rel="stylesheet" href="../../modules/culture/culture-training-controls.css?v=${VERSION}">` : ''}${cultureStyle}
  <script type="module" src="../../modules/pages/class-page.js?v=20260905-universal-v1"></script>
  ${hasProgression ? `<script type="module" src="../../modules/culture/culture-class-page.js?v=${structureOnly ? STRUCTURE_ONLY_VERSION : VERSION}"></script>` : ''}
</head><body class="classes-page class-document-page cenyr-class-page ${escape(culture.id)}-class-page" data-class-document="${document.id}" data-culture="${escape(culture.id)}"${progressionAttribute} data-class-theme="sand" id="top">
  <a class="skip-link" href="#einfuehrung">Zum Klasseninhalt</a>
  <header class="site-header"><a href="../../Klassenseite.html#${escape(culture.id)}">← Zum Klassenregister</a><span class="site-brand">Aleria / ${escape(labels.brand)}</span><a class="class-almanach-link" href="../../../AleriaAlmanach/AleriaAlmanach.html">Zum Almanach</a></header>
  <div class="class-book"><aside class="class-book-navigation"><a class="class-book-mark" href="../../Klassenseite.html#${escape(culture.id)}"><img src="${escape(culture.emblem)}" alt="" width="48" height="48" data-fallback-src="${FALLBACK}"><span>${labels.traditions}</span></a>${renderContents(contents, pending.length > 0)}${cultureNavigation(documents, document.id, culture)}</aside>
  <main class="class-book-page"><header class="class-cover"><div class="class-cover-top"><p class="eyebrow">Kulturklassen · ${escape(culture.name)}</p><span class="class-volume-number">${String(index + 1).padStart(2, '0')} / ${String(documents.length).padStart(2, '0')}</span></div>
    <div class="class-cover-title"><div class="class-emblem"><img src="${escape(document.icon)}" alt="" width="100" height="100" data-role="class-icon" data-fallback-src="${FALLBACK}"></div><div><p class="class-cover-kind">${escape(affiliation)}</p><h1>${escape(document.title)}</h1><p class="class-cover-subtitle">${escape(focus)}</p></div></div>
    <div class="cenyr-cover-path"><span>${escape(culture.name)}</span><span>${escape(document.name)}</span>${hasProgression ? `<a href="#ausbildungsplan">${escape(styleName)} · ${trainingLabel} ↓</a>` : '<a href="#geschichte">Kultur, Rolle &amp; Ausrüstung ↓</a>'}</div>
  </header>
  ${sharedCultureNote(document)}
  <details class="class-mobile-nav"><summary>Inhalt &amp; ${escape(culture.name)}-Klassen</summary>${renderContents(contents, pending.length > 0)}${cultureNavigation(documents, document.id, culture)}</details>
  <div class="class-reading-layout cenyr-introduction"><div class="class-chapters">${renderSection(written[0], 0)}</div><aside class="class-reference" aria-label="Klassenillustration">${renderIllustration(document)}</aside></div>
  ${hasProgression && orderOverview ? renderCultureClassTraining(plan) : orderOverview}
  ${hasProgression && orderOverview ? orderOverview : hasProgression ? renderCultureClassTraining(plan) : ''}
  <div class="class-reading-layout"><div class="class-chapters">${written.slice(1).map((section, index) => renderSection(section, index + 1)).join('\n')}${renderPending(pending)}</div><aside class="class-reference" aria-label="Klassenprofil">${renderFacts(document)}${companion ? renderIllustration({ name: document.name, title: companion.caption, illustration: companion.source, artwork: companion }) : ''}</aside></div>
  <nav class="class-next-pages" aria-label="Weitere ${escape(culture.name)}-Klassen"><a href="${pageHref(previous)}"><span>← Vorherige Klasse</span><strong>${escape(previous.name)}</strong></a><a href="${pageHref(next)}"><span>Nächste Klasse →</span><strong>${escape(next.name)}</strong></a></nav>
  <footer class="catalog-footer"><span>Aleria · Kulturklassen · ${escape(culture.name)}</span><div><button type="button" class="class-print-button" data-action="print-class" hidden>Drucken</button><a href="#top">Nach oben ↑</a></div></footer>
  </main></div>
</body></html>
`.replace(/[\t ]+$/gm, '');
}
