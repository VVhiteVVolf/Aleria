import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import '../../AleriaAlmanach/modules/biography/biography-card-rendering.js';
const directory = new URL('./', import.meta.url);
const { entries } = JSON.parse(await readFile(new URL('sources/public-biographies.json', directory), 'utf8'));
const keys = new Set();
const identities = { characterIds:new Map(), worldPersonIds:new Map(), personIds:new Map() };
const modulePages = new Set();
for (const entry of entries) {
  assert(entry.key && !keys.has(entry.key), `Doppelte Bio: ${entry.key}`); keys.add(entry.key);
  assert(entry.biography?.biography, `Biografie fehlt: ${entry.name}`);
  assert(entry.replacedFingerprints?.length, `Abgleichbeleg fehlt: ${entry.name}`);
  for (const mentor of entry.biography.biography.knightMentors || []) assert(mentor.name && mentor.image, `Ausbildungsperson ohne Portrait: ${entry.name}`);
  for (const [field,index] of Object.entries(identities)) for (const id of entry[field]) {
    assert(!index.has(id) || index.get(id) === entry.key, `Mehrdeutige Bio-Zuordnung: ${field}/${id}`);
    index.set(id,entry.key);
  }
  for (const ref of entry.moduleRefs) {
    const key = `${ref.moduleId}:${ref.pageKey}`;
    assert(ref.moduleId && ref.pageKey && ref.pageKey !== '*', `Biografie benötigt eine konkrete Modulseite: ${entry.name}`);
    assert(!modulePages.has(key), `Doppelte Modul-Biografiezuordnung: ${key}`);
    modulePages.add(key);
  }
}
// This generated bridge supports the existing classic Almanach and ES-module tree.
// It owns immutable editorial defaults, never live state or a second save target.
const runtime = `// Generated by node js/biography/build-public-biographies.mjs.\n(function (root) {
  const rows = ${JSON.stringify(entries.map(({source,name,...entry})=>entry))};
  const characters = new Map(), worlds = new Map(), people = new Map(), modules = new Map();
  for (const row of rows) {
    for (const id of row.characterIds) characters.set(id, row);
    for (const id of row.worldPersonIds) worlds.set(id, row);
    for (const id of row.personIds) people.set(id, row);
    for (const ref of row.moduleRefs) modules.set(ref.moduleId + ':' + ref.pageKey, { row, ref });
  }
  const clone = value => JSON.parse(JSON.stringify(value));
  function apply(stored, row, mentorsOnly = false) {
    if (stored?.disabled === true) return null;
    if (!row) return stored || null;
    if (!stored) return clone(row.biography);
    const data = { ...stored.biography }, baseline = row.biography.biography;
    if (!mentorsOnly && row.replacedFingerprints.includes(root.AleriaBiographyCards.narrativeFingerprint(stored))) {
      // Titles, tables, traits and other authored fields keep their own edits.
      for (const key of ['biographyText', 'historyText', 'extraSections']) {
        if (Object.hasOwn(baseline, key)) data[key] = clone(baseline[key]);
      }
    }
    if (data.knightMentors === undefined && baseline.knightMentors?.length) data.knightMentors = clone(baseline.knightMentors);
    return { ...stored, biography: data };
  }
  function resolve(stored, { characterId, worldPersonId, personId } = {}) {
    const row = worlds.get(worldPersonId) || characters.get(characterId) || people.get(personId);
    // An explicit world identity outranks historical character or tree aliases.
    if (worldPersonId && row && !row.worldPersonIds.includes(worldPersonId)) return stored || null;
    return apply(stored, row);
  }
  function resolveModule(page, moduleId) {
    const item = modules.get(moduleId + ':' + (page.commentThreadKey || page.pageTitle));
    if (!item) return page;
    const stored = { biography: { ...page.biography, biographyText: page.biography?.biographyText || page.description || '' } };
    return { ...page, biography: apply(stored, item.row, item.ref.mentorsOnly).biography };
  }
  root.AleriaBiographyCatalog = Object.freeze({ resolve, resolveModule });
})(globalThis);\n`;
const target = new URL('public-biographies.generated.js', directory);
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), runtime, 'Biografie-Katalog veraltet.');
else await writeFile(target, runtime);
console.log(`${entries.length} öffentliche Biografien; ${entries.filter(e=>e.biography.biography.knightMentors?.length).length} mit belegter Ausbildung. ${fileURLToPath(target)}`);
