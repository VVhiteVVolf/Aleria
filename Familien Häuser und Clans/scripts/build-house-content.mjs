import { readFile, writeFile, readdir } from 'node:fs/promises';
import { relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHousePageData, createHouseBiography } from '../modules/house-content/house-content-outputs.mjs';
import { parseHouseScope, selectHouseSources, mergePageRegistry, mergeRankRegistry, mergeBiographyRegistry } from './house-content-scope.mjs';

const featureRoot = new URL('../', import.meta.url);
const checkOnly = process.argv.includes('--check');
const header = '// Generated by scripts/build-house-content.mjs. Edit haus.content.mjs instead.\n';
const defaultContentVersion = 'gwendolyn-20260911h';
const houseIds = parseHouseScope(process.argv.slice(2));

// Discover authoring modules at build time; each house retains its own editable source.
async function findSources(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const sources = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const url = new URL(`${encodeURIComponent(entry.name)}${entry.isDirectory() ? '/' : ''}`, directory);
    if (entry.isDirectory()) sources.push(...await findSources(url));
    else if (entry.name === 'haus.content.mjs') sources.push(url);
  }
  return sources;
}

async function output(target, text) {
  const previous = await readFile(target, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error;
    return null;
  });
  if (checkOnly) {
    if (previous !== text) throw new Error(`${fileURLToPath(target)} ist nicht aktuell.`);
  } else if (previous !== text) await writeFile(target, text, 'utf8');
}

const relativePath = (base, target) => relative(fileURLToPath(base), fileURLToPath(target)).replaceAll('\\', '/');
const authoringRoots = ['Estryll', 'Lothir', 'Aldervan'];
export const HOUSE_SOURCES = (await Promise.all(authoringRoots.map(async continent => {
  try { return await findSources(new URL(`${continent}/`, featureRoot)); }
  catch (error) { if (error.code === 'ENOENT') return []; throw error; }
}))).flat();
const pageEntries = [];
const houseRanks = {};
const biographyImports = [];
const biographyEntries = [];
const biographyRegistry = new URL('../Stammbäume/assets/js/data/house-biographies.registry.js', featureRoot);
const pendingOutputs = [];
const loadedSources = await Promise.all(HOUSE_SOURCES.map(async sourceUrl => ({ sourceUrl, content: (await import(sourceUrl.href)).HOUSE_CONTENT })));
const selectedSources = selectHouseSources(loadedSources, houseIds);
const sourceOrder = loadedSources.map(source => source.content.id);

for (const { sourceUrl, content } of selectedSources) {
  const contentVersion = content.contentVersion || defaultContentVersion;
  houseRanks[content.id] = content.profile.rank || content.profile.highestTitle || '';
  pendingOutputs.push([new URL('haus.data.js', sourceUrl), `${header}window.HAEUSER_DATA = ${JSON.stringify(createHousePageData(content), null, 2)};\n`]);
  if (!content.biographyManagedExternally) {
    pendingOutputs.push([new URL('haus.biography.mjs', sourceUrl), `${header}export const HOUSE_BIOGRAPHY = ${JSON.stringify(createHouseBiography(content), null, 2)};\n`]);
  }
  if (content.registerPage) {
    pageEntries.push({ id: content.id, slug: content.id, aliases: [...(content.aliases || [])], name: content.name, status: 'active', type: content.type === 'Clan' ? 'clan' : content.type === 'Bürgerliches Haus' ? 'family' : 'house', page: content.page || 'haus.html', data: `${relativePath(featureRoot, new URL('haus.data.js', sourceUrl))}?v=${contentVersion}`, hierarchy: content.hierarchy, tags: [content.county, content.type], prepared: content.prepared === true });
  }
  if (content.biographySourceRevision) {
    const identifier = content.id.replaceAll('-', '_');
    const importPath = relative(dirname(fileURLToPath(biographyRegistry)), fileURLToPath(new URL('haus.biography.mjs', sourceUrl))).replaceAll('\\', '/');
    biographyImports.push(`import { HOUSE_BIOGRAPHY as ${identifier} } from ${JSON.stringify(`${importPath}?v=${contentVersion}`)};`);
    const previousDefaults = content.biographyPreviousDefaultFingerprints || [];
    biographyEntries.push(`  ${JSON.stringify(content.id)}: Object.freeze({ sourceRevision: ${content.biographySourceRevision}, biography: ${identifier}, replacedDefaultFingerprints: Object.freeze(${JSON.stringify(previousDefaults)}) }),`);
  }
  console.log(`${content.id}: Hausseite und Hausbio ${checkOnly ? 'aktuell' : 'erstellt'}.`);
}

pendingOutputs.push([biographyRegistry, houseIds
  ? mergeBiographyRegistry(await readFile(biographyRegistry, 'utf8'), biographyImports, biographyEntries, houseIds, sourceOrder, header)
  : `${header}${biographyImports.join('\n')}\n\nexport const HOUSE_BIOGRAPHY_DEFAULTS = Object.freeze({\n${biographyEntries.join('\n')}\n});\n`]);
const rankRegistry = new URL('modules/house-content/house-ranks.generated.mjs', featureRoot);
pendingOutputs.push([rankRegistry, houseIds
  ? mergeRankRegistry(await readFile(rankRegistry, 'utf8'), houseRanks, houseIds, sourceOrder, header)
  : `${header}export const HOUSE_RANKS = Object.freeze(${JSON.stringify(houseRanks, null, 2)});\n`]);
const pageRegistry = new URL('haeuser.registry.js', featureRoot);
const registrySource = await readFile(pageRegistry, 'utf8');
const generatedBlock = `    // BEGIN GENERATED HOUSE PAGES\n${pageEntries.map(entry => `    ${JSON.stringify(entry)},`).join('\n')}\n    // END GENERATED HOUSE PAGES`;
if (!registrySource.includes('// BEGIN GENERATED HOUSE PAGES')) throw new Error('Registry-Ausgabebereich fehlt.');
pendingOutputs.push([pageRegistry, houseIds ? mergePageRegistry(registrySource, pageEntries, houseIds, sourceOrder)
  : registrySource.replace(/    \/\/ BEGIN GENERATED HOUSE PAGES[\s\S]*?    \/\/ END GENERATED HOUSE PAGES/, generatedBlock)]);

// Resolve scopes and validate every shared registry before the first write.
for (const [target, text] of pendingOutputs) await output(target, text);
