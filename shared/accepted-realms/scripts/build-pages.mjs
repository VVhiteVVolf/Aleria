import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { realms, realmsById, placeId } from '../catalog.mjs';
import { createTerritoryArticle } from '../territory-article.mjs';
import { createAcceptedPlace } from '../place-content.mjs';
import { buildTerritoryRegion } from '../../../Kontinente/scripts/territory-region-build.mjs';
import { buildAtlasPages } from './atlas-pages.mjs';

const root = new URL('../../../', import.meta.url), check = process.argv.includes('--check');
const version = 'accepted-realms-20261029a';
async function output(file, text) {
  const url = new URL(file, root);
  const previous = await readFile(url, 'utf8').catch(e => { if (e.code !== 'ENOENT') throw e; return null; });
  if (check) { if (text !== previous) throw Error(`Veraltet: ${file}`); }
  else if (previous !== text) { await mkdir(new URL('./', url), { recursive: true }); await writeFile(url, text); }
}
const json = data => JSON.stringify(data, null, 2) + '\n';
const moduleImport = (target, from) => { const relative = path.relative(path.dirname(fileURLToPath(new URL(from, root))), fileURLToPath(new URL(target, root))).replaceAll('\\', '/'); return relative.startsWith('.') ? relative : './' + relative; };

const ortEntries = [];
for (const realm of realms) {
  const moduleRoot = `Kontinente/modules/${realm.id}`;
  const pages = realm.territories.map(t => createTerritoryArticle(realm, t));
  await output(`${moduleRoot}/pages.source.json`, json({ pages }));
  await output(`${moduleRoot}/territory-page.mjs`, `// Shared accepted source; each country keeps its own page boundary.\nimport { createAcceptedTerritory } from '../accepted-realms/territory-page.mjs?v=${version}';\nexport const createTerritory = (id, data) => createAcceptedTerritory('${realm.id}', id, data);\n`);
  await output(`Karten/${realm.name}/territories.import.json`, json({ territories: realm.territories }));
  await buildTerritoryRegion({ slug: realm.id, region: realm.name, kingdom: realm.name, version, mapFolder: realm.name, check });
  for (const house of realm.houses) {
    const origin = realmsById.get(house.originRealm) || realm;
    const file = `Familien Häuser und Clans/${origin.continent}/${origin.name}/${house.familyId}/haus.content.mjs`;
    await output(file, `// House-specific authoring boundary; accepted facts remain shared with the territorial register.\nimport { realmsById } from '${moduleImport('shared/accepted-realms/catalog.mjs', file)}';\nimport { createAcceptedHouseContent } from '${moduleImport('shared/accepted-realms/house-content.mjs', file)}';\nconst realm = realmsById.get('${realm.id}');\nexport const HOUSE_CONTENT = createAcceptedHouseContent(realm, realm.housesById.get('${house.id}'));\n`);
  }
  for (const seat of realm.settlements) {
    const origin = realmsById.get(seat.originRealm) || realm;
    const id = placeId(realm, seat);
    const file = `Orte/${origin.continent}/${origin.name}/${seat.county || seat.province || 'Stadtgebiete'}/${seat.id}/ort.data.js`;
    const data = createAcceptedPlace(realm, seat);
    await output(file, `// Generated by shared/accepted-realms/scripts/build-pages.mjs.\nwindow.ORT_DATA = ${JSON.stringify(data, null, 2)};\n`);
    ortEntries.push({ id, slug: id, name: seat.name, status: 'draft', type: data.meta.type.toLowerCase(), data: file.slice('Orte/'.length) + '?v=' + version,
      inlineCollection: 'orte_inline_content', sceneCollection: 'orte_scenes', hierarchy: data.hierarchy, tags: ['orte', origin.id, ...(realm.occupied ? ['besetzt'] : []), ...(realm.historical ? ['historisch'] : [])] });
  }
}
const registryFile = 'Orte/orte.registry.js', registry = await readFile(new URL(registryFile, root), 'utf8');
const block = `  // BEGIN ACCEPTED_REALMS_GENERATED\n${ortEntries.map(e => '  ' + JSON.stringify(e) + ',').join('\n')}\n  // END ACCEPTED_REALMS_GENERATED\n`;
const matcher = /  \/\/ BEGIN ACCEPTED_REALMS_GENERATED\r?\n[\s\S]*?  \/\/ END ACCEPTED_REALMS_GENERATED\r?\n/;
const next = matcher.test(registry) ? registry.replace(matcher, block) : registry.replace(/(window\.ORTE_REGISTRY\s*=\s*\[\r?\n)/, '$1' + block);
if (!next.includes('// BEGIN ACCEPTED_REALMS_GENERATED')) throw Error('Ortsregister nicht erkannt.');
await output(registryFile, next);
console.log(`${ortEntries.length} Ortsakten und ${realms.reduce((n, r) => n + r.houses.length, 0)} Hausquellen ${check ? 'geprüft' : 'angelegt'}.`);
await buildAtlasPages(output, file => readFile(new URL(file, root), 'utf8'));
