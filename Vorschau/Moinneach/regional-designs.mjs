export function withRegionalDesigns(proposal){
 if(proposal.id==='original')return {...proposal,regions:proposal.regions.map(region=>({
  ...region,design:{...individualBanners[region.id],kind:'banner-only',name:region.label,
   byname:'Stadtgebiet',meaning:null,source:null,
   landscape:proposal.settlements.find(place=>place.id===region.id).geography}
 }))};
 const designs=regionalDesigns[proposal.id];
 return designs?{...proposal,regions:proposal.regions.map(region=>({...region,design:designs[region.id]}))}:proposal;
}
