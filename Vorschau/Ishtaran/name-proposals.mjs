/**
 * Unzugeordnete Namensvorschläge für die lokale Ishtaran-Werkstatt.
 * Klangvorschläge begründen weder Häuser noch Orte, Ränge oder Besitzrechte.
 * Historische Anklänge stammen aus der Nutzerliste und wurden hier nicht
 * als sprachwissenschaftliche oder historische Herleitungen verifiziert.
 */

function createProposals(kind, group, entries) {
  return entries.map(([name, note, stableId]) => Object.freeze({
    id: stableId || `${kind}-${name.toLowerCase()
      .replaceAll('ä', 'ae').replaceAll('ö', 'oe').replaceAll('ü', 'ue')
      .replaceAll('ß', 'ss').replace(/[^a-z0-9]+/g, '-')}`,
    name,
    group,
    note,
    status: 'proposal',
  }));
}

