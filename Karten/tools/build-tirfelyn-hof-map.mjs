import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { buildHofMap, hofMapConfig, hofMapRegistryEntry, HOF_MAP_LINK } from '../modules/tirfelyn-hof/hof-map.mjs';
import { HOF_MAP_FOLDER } from '../../shared/tirfelyn-hof/hof-pois.mjs';
import { writeGeneratedMap, updateGeneratedMapRegistry } from './generated-map-output.mjs';
import { HOF_MARKER_DEFINITIONS } from '../modules/tirfelyn-hof/hof-markers.mjs';

if (process.argv.slice(2).some(arg => arg !== '--check')) throw Error('Verwendung: build-tirfelyn-hof-map.mjs [--check]');
const check = process.argv.includes('--check'), root = new URL('../', import.meta.url);
await writeGeneratedMap(root, `${HOF_MAP_FOLDER}/data.json`, buildHofMap(), { check });
const configPath = new URL(`${HOF_MAP_FOLDER}/template.config.js`, root);
const configText = `// Generated by Karten/tools/build-tirfelyn-hof-map.mjs.\nwindow.KARTO_CONFIG = ${JSON.stringify(hofMapConfig(), null, 2)};\n`;
if (check) assert.equal(await readFile(configPath, 'utf8'), configText, 'Veraltete Hofkarten-Konfiguration');
else { await mkdir(new URL('.', configPath), { recursive: true }); await writeFile(configPath, configText); }
await updateGeneratedMapRegistry(root, 'TIRFELYN_HOF', [hofMapRegistryEntry()], { check });

const catalogPath = new URL('assets/js/data/default-marker-catalog.js', root);
const catalog = await readFile(catalogPath, 'utf8');
const catalogBlock = ',\n  // BEGIN TIRFELYN_HOF_MARKERS\n' + HOF_MARKER_DEFINITIONS.map(({ id, url, name, group }) =>
  JSON.stringify({ id, url, name, group }, null, 2).split('\n').map(line => '  ' + line).join('\n')).join(',\n') + '\n  // END TIRFELYN_HOF_MARKERS';
const catalogPattern = /,\r?\n  \/\/ BEGIN TIRFELYN_HOF_MARKERS\r?\n[\s\S]*?  \/\/ END TIRFELYN_HOF_MARKERS/;
const nextCatalog = catalogPattern.test(catalog) ? catalog.replace(catalogPattern, catalogBlock) : catalog.replace(/\r?\n\];\s*$/, catalogBlock + '\n];\n');
assert.ok(nextCatalog.includes('// BEGIN TIRFELYN_HOF_MARKERS'), 'Marker-Katalog nicht erkannt');
if (check) assert.equal(catalog, nextCatalog, 'Hofpins fehlen im bestehenden Marker-Katalog');
else await writeFile(catalogPath, nextCatalog);

// Only the existing Tirfelyn record is patched; all neighbouring pins remain untouched.
const parent = 'Cenyr/celtigerns-wacht/llamrais-ankunft/gwynthor-bannkreis/';
const mapPath = new URL(`${parent}data.json`, root), sourcePath = new URL(`${parent}fleischsammler-localities.source.json`, root);
const map = JSON.parse(await readFile(mapPath, 'utf8')), source = JSON.parse(await readFile(sourcePath, 'utf8'));
const pin = map.state.pins.find(pin => pin.id === 'gwynthor-marking-107');
const location = source.locations.find(location => location.pinId === pin.id);
const otherPins = JSON.stringify(map.state.pins.filter(candidate => candidate.id !== pin.id));
const otherLocations = JSON.stringify(source.locations.filter(candidate => candidate.pinId !== pin.id));
const sceneImage = '/AleriaAlmanach/assets/tirfelyn-hof/scenes/bauernherrenhaus-v1.png';
const textLink = `[URL=${HOF_MAP_LINK}]Ortskarte des Tirfelyn-Hofs öffnen[/URL]`;
let changed = false;
for (const target of [pin, location.patch]) {
  for (const [key, value] of Object.entries({ img: sceneImage, imgLink: HOF_MAP_LINK })) {
    if (target[key] !== value) { if (check) throw Error(`Hofkartenlink fehlt: ${key}`); target[key] = value; changed = true; }
  }
  if (!target.text.includes(textLink)) { if (check) throw Error('Hofkarten-Textlink fehlt'); target.text += `\n\n${textLink}`; changed = true; }
}
assert.equal(JSON.stringify(map.state.pins.filter(candidate => candidate.id !== pin.id)), otherPins);
assert.equal(JSON.stringify(source.locations.filter(candidate => candidate.pinId !== pin.id)), otherLocations);
if (changed) { map.revision++; map.updatedAt = new Date().toISOString(); await writeFile(mapPath, JSON.stringify(map, null, 2) + '\n'); await writeFile(sourcePath, JSON.stringify(source, null, 2) + '\n'); }
console.log(JSON.stringify({ pins: 16, rasterLayers: 2, peopleLayer: true, markerTypes: 9, check, parentLinkChanged: changed, deployed: false }));
