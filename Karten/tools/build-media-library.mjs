import { createHash } from 'node:crypto';
import { readdir, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDir = path.dirname(fileURLToPath(import.meta.url));
const mapsDir = path.resolve(toolsDir, '..');
const repoDir = path.resolve(mapsDir, '..');
const outputFile = path.join(mapsDir, 'assets', 'js', 'media', 'media-assets.registry.js');
const imageExtensions = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg']);

const sources = [
  {
    directory: path.join(mapsDir, 'assets', 'icons'),
    publicRoot: '/Karten/assets/icons',
    kind: 'marker',
    source: 'Kartenzeichen & Map-Pins',
  },
  {
    directory: path.join(repoDir, 'Stammbäume', 'assets', 'images', 'houses'),
    publicRoot: '/Stammbäume/assets/images/houses',
    kind: 'crest',
    source: 'Hauswappen',
  },
  {
    directory: path.join(repoDir, 'Stammbäume', 'assets', 'images', 'regions'),
    publicRoot: '/Stammbäume/assets/images/regions',
    kind: 'region',
    source: 'Orts- & Regionsbanner',
  },
];

function publicPath(root, relativePath) {
  return `${root}/${relativePath.split(path.sep).map(encodeURIComponent).join('/')}`;
}

function displayName(fileName) {
  return path.basename(fileName, path.extname(fileName)).replace(/[_-]+/g, ' ').replace(/\s+/g, ' ').trim();
}

async function scan(source, directory = source.directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const assets = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      assets.push(...await scan(source, absolute));
      continue;
    }
    if (!entry.isFile() || !imageExtensions.has(path.extname(entry.name).toLowerCase())) continue;
    const relative = path.relative(source.directory, absolute);
    const groupPath = path.dirname(relative);
    const group = groupPath === '.' ? source.source : groupPath.split(path.sep).join(' / ');
    const url = publicPath(source.publicRoot, relative);
    assets.push({
      id: createHash('sha1').update(url).digest('hex').slice(0, 14),
      name: displayName(entry.name),
      url,
      kind: source.kind,
      group,
      source: source.source,
    });
  }
  return assets;
}

const assets = (await Promise.all(sources.map(source => scan(source))))
  .flat()
  .sort((a, b) => a.kind.localeCompare(b.kind, 'de') || a.group.localeCompare(b.group, 'de') || a.name.localeCompare(b.name, 'de'));

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(
  outputFile,
  `// Generated by Karten/tools/build-media-library.mjs — do not edit by hand.\nwindow.KARTO_MEDIA_ASSETS = Object.freeze(${JSON.stringify(assets, null, 2)});\n`,
  'utf8',
);

console.log(`Karten-Mediathek: ${assets.length} Bilddateien registriert.`);
